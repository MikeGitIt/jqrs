/// Block operations
pub fn block_join(mut a: Block, mut b: Block) -> Block {
    let debug = std::env::var("DEBUG_PARSER").is_ok();
    if debug {
        eprintln!("PARSER block_join: a.first={} a.last={} b.first={} b.last={}",
                 a.first.is_some(), a.last.is_some(), b.first.is_some(), b.last.is_some());
    }
    if a.first.is_none() {
        return b;
    }
    if b.first.is_none() {
        return a;
    }
    // Link a's last instruction to b's first instruction
    if let (Some(a_last_ptr), Some(ref mut b_first)) = (a.last, &mut b.first) {
        unsafe {
            if let Some(a_last) = a_last_ptr.as_mut() {
                if debug { eprintln!("PARSER block_join: linking blocks"); }
                b_first.prev = Some(a_last);
                a_last.next = Some(std::mem::take(b_first));
            } else {
                if debug { eprintln!("PARSER block_join: a_last is NULL"); }
            }
        }
    } else {
        if debug { eprintln!("PARSER block_join: pattern match failed"); }
    }
    Block {
        first: a.first,
        last: b.last,
    }
}
