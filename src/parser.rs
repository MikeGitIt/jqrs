/// Parse a jq program from a location file
///
/// # Arguments
/// * `locations` - The source file with location information
/// * `answer` - Output parameter for the parsed block
///
/// # Returns
/// The number of parse errors (0 on success)
pub fn jq_parse<T>(locations: &mut Locfile<T>, answer: &mut Block) -> i32 {
    let mut lexer = match jq_yylex_init_extra(0) {
        Ok(lex) => lex,
        Err(_) => return 1,
    };

    // Scan the input bytes into the lexer
    let buf = jq_yy_scan_bytes(locations.data.as_bytes(), &mut lexer);

    // Create LexerParam with pointer to lexer state
    let mut lexer_param = LexerParam {
        scanner: Some(&mut *lexer as *mut _),
    };

    let mut errors = 0i32;
    *answer = gen_noop();

    let debug_parse = std::env::var("DEBUG_PARSE").is_ok();
    if debug_parse { eprintln!("DEBUG jq_parse: calling yyparse, input len={}", locations.data.len()); }

    // Call the actual parser
    let parse_result = yyparse(answer, &mut errors, locations, &mut lexer_param);
    if debug_parse { eprintln!("DEBUG jq_parse: yyparse returned {}, errors={}", parse_result, errors); }

    if parse_result != 0 && errors == 0 {
        errors = 1;
        if locations.error.is_none() {
            locations.error = Some(format!("jq: error: syntax error at {}, line 1:", locations.fname));
        }
    }

    // Clean up lexer resources
    jq_yy_delete_buffer(Some(buf), &mut lexer);
    jq_yylex_destroy(&mut lexer);

    // If there were errors, free the answer and return a noop
    if errors > 0 || parse_result != 0 {
        block_free(std::mem::take(answer));
        *answer = gen_noop();
    }

    errors
}
