/// Generate a define-or-assign expression block
///
/// Creates a block that performs a define-or assignment operation,
/// which assigns a value only if the path doesn't exist or is null.
pub fn gen_definedor_assign(object: Block, val: Block) -> Block {
    let tmp = crate::compile::gen_op_var_fresh(crate::compile::STOREV, "tmp");
    let load_tmp = crate::compile::gen_op_bound(crate::compile::LOADV, &tmp);
    let lambda1 = gen_lambda(object);
    let lambda2 = gen_lambda(gen_definedor(gen_noop(), load_tmp));
    let modify_call = gen_call("_modify", block_join(lambda1, lambda2));
    let prefix = block_join(block_join(gen_op_simple(OpCode::Dup), val), tmp);
    block_join(prefix, modify_call)
}
/// Copy a string into a Vec<u8> buffer, returning the index of the last character
///
/// # Arguments
/// * `yydest` - Destination buffer
/// * `yysrc` - Source bytes
///
/// # Returns
/// Index pointing to the position after the last copied character
fn yystpcpy_bytes(yydest: &mut Vec<u8>, yysrc: &[u8]) -> usize {
    let start = yydest.len();
    for &byte in yysrc {
        if byte == 0 {
            break;
        }
        yydest.push(byte);
    }
    yydest.push(0);
    yydest.len() - 1
}
impl YYSType {
    pub fn literal(&self) -> Option<&Jv> {
        match self {
            YYSType::Literal(jv) => Some(jv),
            _ => None,
        }
    }
    pub fn literal_mut(&mut self) -> Option<&mut Jv> {
        match self {
            YYSType::Literal(jv) => Some(jv),
            _ => None,
        }
    }
    pub fn blk(&self) -> Option<&Block> {
        match self {
            YYSType::Blk(b) => Some(b),
            _ => None,
        }
    }
    /// Take (move) a block out of this YYSType, replacing it with a noop
    /// This avoids expensive cloning of block instruction lists
    pub fn take_blk(&mut self) -> Block {
        match std::mem::take(self) {
            YYSType::Blk(b) => b,
            _ => gen_noop(),
        }
    }
}
/// Locfile simplified structure for this module
impl Locfile {
    pub fn new(fname: &str, data: &str) -> Self {
        let mut linemap = vec![0];
        for (i, c) in data.char_indices() {
            if c == '\n' {
                linemap.push(i as i32 + 1);
            }
        }
        let nlines = linemap.len() as i32;
        Locfile {
            fname: fname.to_string(), // fname is String, not Jv
            data: data.to_string(),
            length: data.len() as i32,
            linemap,
            nlines,
            error: None,
            jq: None,
            refct: 1,
        }
    }
}
