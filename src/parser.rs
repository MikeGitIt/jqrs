/// Generate a slice index expression block
///
/// Creates a block that performs array slicing with start and end indices.
/// Matches C implementation: gen_slice_index in parser.y:191
pub fn gen_slice_index(obj: Block, start: Block, end: Block, idx_op: OpCode) -> Block {
    // Build key object: {start: <start>, end: <end>}
    // C: block key = BLOCK(gen_subexp(gen_const(jv_object())),
    //                      gen_subexp(gen_const(jv_string("start"))),
    //                      gen_subexp(start),
    //                      gen_op_simple(INSERT),
    //                      gen_subexp(gen_const(jv_string("end"))),
    //                      gen_subexp(end),
    //                      gen_op_simple(INSERT));
    let key1 = block_join(
        gen_subexp(gen_const(jv_object())),
        gen_subexp(gen_const(jv_string("start"))),
    );
    let key2 = block_join(key1, gen_subexp(start));
    let key3 = block_join(key2, gen_op_simple(OpCode::Insert));
    let key4 = block_join(key3, gen_subexp(gen_const(jv_string("end"))));
    let key5 = block_join(key4, gen_subexp(end));
    let key = block_join(key5, gen_op_simple(OpCode::Insert));
    // C: return BLOCK(key, obj, gen_op_simple(idx_op));
    let result1 = block_join(key, obj);
    block_join(result1, gen_op_simple(idx_op))
}
