/// Calculate number of units for given digits using lookup table
fn d2u(digits: i32) -> usize {
    if digits <= 49 {
        D2UTABLE[digits as usize] as usize
    } else {
        ((digits + DECDPUN - 1) / DECDPUN) as usize
    }
}
/// Copy a DecNumber
pub fn decNumberCopy<'a>(dest: &'a mut DecNumber, src: &DecNumber) -> &'a mut DecNumber {
    dest.digits = src.digits;
    dest.exponent = src.exponent;
    dest.bits = src.bits;
    let units = d2u(src.digits) as usize;
    dest.lsu.clear();
    dest.lsu.extend_from_slice(&src.lsu[..units.min(src.lsu.len())]);
    while dest.lsu.len() < units {
        dest.lsu.push(0);
    }
    dest
}
