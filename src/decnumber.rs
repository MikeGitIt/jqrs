/// Fused multiply-add: res = lhs * rhs + fhs
pub fn decNumberFMA<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    fhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    let mut status: u32 = 0;
    loop {
        if (!lhs.is_special() && decCheckMath(lhs, set, &mut status) != 0)
            || (!rhs.is_special() && decCheckMath(rhs, set, &mut status) != 0)
            || (!fhs.is_special() && decCheckMath(fhs, set, &mut status) != 0)
        {
            break;
        }
        let mut dcmul = set.clone();
        dcmul.digits = lhs.digits + rhs.digits;
        dcmul.emax = DEC_MAX_EMAX;
        dcmul.emin = DEC_MIN_EMIN;
        let need_units = d2u(dcmul.digits) as usize;
        let mut acc = DecNumber::with_capacity(need_units);
        decMultiplyOp(&mut acc, lhs, rhs, &dcmul, &mut status);
        if (status & DEC_INVALID_OPERATION) != 0 {
            if (status & DEC_INEXACT) == 0 {
                decNumberZero(res);
                res.bits = DECNAN;
                break;
            }
            let dzero = DecNumber::default();
            decAddOp(res, &acc, &dzero, set, 0, &mut status);
        } else {
            decAddOp(res, &acc, fhs, set, 0, &mut status);
        }
        break;
    }
    if status != 0 {
        decStatus(res, status, set);
    }
    res
}
