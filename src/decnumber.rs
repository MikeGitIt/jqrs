/// Classify a decimal number
pub fn decNumberClass(dn: &DecNumber, set: &DecContext) -> DecClass {
    if dn.is_special() {
        if dn.is_qnan() {
            return DecClass::Qnan;
        }
        if dn.is_snan() {
            return DecClass::Snan;
        }
        if dn.is_negative() {
            return DecClass::NegInf;
        }
        return DecClass::PosInf;
    }
    if decNumberIsNormal(dn, set) {
        if dn.is_negative() {
            return DecClass::NegNormal;
        }
        return DecClass::PosNormal;
    }
    if dn.is_zero() {
        if dn.is_negative() {
            return DecClass::NegZero;
        }
        return DecClass::PosZero;
    }
    if dn.is_negative() {
        return DecClass::NegSubnormal;
    }
    DecClass::PosSubnormal
}
