/// Digits to units lookup table (for small values)
fn d2utable(digits: i32) -> i32 {
    if digits <= 49 {
        (digits + DECDPUN - 1) / DECDPUN
    } else {
        (digits + DECDPUN - 1) / DECDPUN
    }
}
/// Convert DecNumber to string representation
pub fn decNumberToString(dn: &DecNumber) -> String {
    if dn.is_nan() {
        if dn.is_snan() {
            return "sNaN".to_string();
        }
        return "NaN".to_string();
    }
    if dn.is_infinite() {
        if dn.is_negative() {
            return "-Infinity".to_string();
        }
        return "Infinity".to_string();
    }
    let mut result = String::new();
    if dn.is_negative() {
        result.push('-');
    }
    let mut digits = Vec::with_capacity(dn.digits as usize);
    let units = d2u(dn.digits) as usize;
    for i in 0..units {
        let u = dn.lsu.get(i).copied().unwrap_or(0);
        digits.push((u % 10) as u8);
        digits.push(((u / 10) % 10) as u8);
        digits.push((u / 100) as u8);
    }
    digits.truncate(dn.digits as usize);
    digits.reverse();
    let exp = dn.exponent;
    if exp == 0 {
        for d in digits {
            result.push((b'0' + d) as char);
        }
    } else if exp > 0 && exp <= 6 {
        for d in digits {
            result.push((b'0' + d) as char);
        }
        for _ in 0..exp {
            result.push('0');
        }
    } else if exp < 0 && exp >= -(dn.digits as i32) {
        let point_pos = (dn.digits + exp) as usize;
        for (i, d) in digits.iter().enumerate() {
            if i == point_pos {
                result.push('.');
            }
            result.push((b'0' + d) as char);
        }
    } else {
        for (i, d) in digits.iter().enumerate() {
            if i == 1 && digits.len() > 1 {
                result.push('.');
            }
            result.push((b'0' + d) as char);
        }
        result.push('E');
        let adjusted_exp = exp + dn.digits - 1;
        if adjusted_exp >= 0 {
            result.push('+');
        }
        result.push_str(&adjusted_exp.to_string());
    }
    result
}
/// Internal helper to convert DecNumber to string
fn decToString(dn: &DecNumber, string: &mut String, engineering: bool) {
    string.clear();
    if dn.is_nan() {
        if dn.is_negative() {
            string.push('-');
        }
        if dn.is_snan() {
            string.push_str("sNaN");
        } else {
            string.push_str("NaN");
        }
        return;
    }
    if dn.is_infinite() {
        if dn.is_negative() {
            string.push('-');
        }
        string.push_str("Infinity");
        return;
    }
    if dn.is_negative() {
        string.push('-');
    }
    if dn.is_zero() {
        string.push('0');
        if dn.exponent != 0 {
            string.push_str(&format!("E{:+}", dn.exponent));
        }
        return;
    }
    let mut digits = Vec::new();
    for &unit in dn.lsu.iter().rev() {
        let s = format!("{:03}", unit);
        for c in s.chars() {
            digits.push(c);
        }
    }
    while digits.len() > 1 && digits[0] == '0' {
        digits.remove(0);
    }
    let actual_digits = dn.digits as usize;
    if digits.len() > actual_digits {
        let excess = digits.len() - actual_digits;
        digits = digits[excess..].to_vec();
    }
    let adjusted_exp = dn.exponent + (dn.digits - 1);
    if dn.exponent <= 0 && adjusted_exp >= -6 {
        if dn.exponent >= 0 {
            for c in &digits {
                string.push(*c);
            }
            for _ in 0..dn.exponent {
                string.push('0');
            }
        } else {
            let point_pos = (dn.digits + dn.exponent) as i32;
            if point_pos <= 0 {
                string.push_str("0.");
                for _ in 0..(-point_pos) {
                    string.push('0');
                }
                for c in &digits {
                    string.push(*c);
                }
            } else {
                for (i, c) in digits.iter().enumerate() {
                    if i == point_pos as usize {
                        string.push('.');
                    }
                    string.push(*c);
                }
            }
        }
    } else {
        let mut exp = adjusted_exp;
        if engineering && exp != 0 {
            let adj = ((exp % 3) + 3) % 3;
            exp -= adj;
        }
        let pre_point = if engineering {
            ((adjusted_exp - exp) + 1) as usize
        } else {
            1
        };
        for (i, c) in digits.iter().enumerate() {
            if i == pre_point && i < digits.len() {
                string.push('.');
            }
            string.push(*c);
        }
        string.push('E');
        if exp >= 0 {
            string.push('+');
        }
        string.push_str(&exp.to_string());
    }
}
