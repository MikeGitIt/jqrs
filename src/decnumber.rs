/// Extract BCD digits from a DecNumber
pub fn decNumberGetBCD<'a>(dn: &DecNumber, bcd: &'a mut [u8]) -> &'a mut [u8] {
    let digits = dn.digits as usize;
    if bcd.len() < digits {
        return bcd;
    }
    let mut bcd_idx = digits;
    let mut unit_idx = 0;
    let mut u = dn.lsu.get(0).copied().unwrap_or(0) as u32;
    let mut cut = DECDPUN;
    while bcd_idx > 0 {
        bcd_idx -= 1;
        bcd[bcd_idx] = (u % 10) as u8;
        u /= 10;
        cut -= 1;
        if cut == 0 && bcd_idx > 0 {
            unit_idx += 1;
            u = dn.lsu.get(unit_idx).copied().unwrap_or(0) as u32;
            cut = DECDPUN;
        }
    }
    &mut bcd[..digits]
}
/// Check if two DecNumbers have the same quantum
pub fn decNumberSameQuantum<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
) -> &'a mut DecNumber {
    let mut ret: u16 = 0;
    if ((lhs.bits | rhs.bits) & DECSPECIAL) != 0 {
        if lhs.is_nan() && rhs.is_nan() {
            ret = 1;
        } else if lhs.is_infinite() && rhs.is_infinite() {
            ret = 1;
        }
    } else if lhs.exponent == rhs.exponent {
        ret = 1;
    }
    decNumberZero(res);
    res.lsu[0] = ret;
    res
}
