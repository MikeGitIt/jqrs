/// Round to integral value with exact flag
pub fn decNumberToIntegralExact<'a>(
    res: &'a mut DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    let mut status: u32 = 0;
    if (rhs.bits & DECSPECIAL) != 0 {
        if dec_number_is_infinite(rhs) {
            decNumberCopy(res, rhs);
        } else {
            decNaNs(res, rhs, None, set, &mut status);
        }
    } else {
        if rhs.exponent >= 0 {
            return decNumberCopy(res, rhs);
        }
        let mut workset = set.clone();
        workset.digits = rhs.digits;
        workset.traps = 0;
        let mut dn = DecNumber::new();
        decNumberZero(&mut dn);
        decNumberQuantize(res, rhs, &dn, &mut workset);
        status |= workset.status;
    }
    if status != 0 {
        decStatus(res, status, set);
    }
    res
}
const BIGODD: i32 = i32::MIN + 3;
const DECNUMMAXE: i32 = 999999999;
const DECNUMMINE: i32 = -999999999;
/// Increment a unit array by 1
fn decUnitIncrement(lsu: &mut [u16], units: usize) {
    for i in 0..units {
        lsu[i] += 1;
        if lsu[i] < 1000 {
            return;
        }
        lsu[i] = 0;
    }
}
/// Trim trailing zeros from a decimal number
fn decTrim<'a>(
    dn: &'a mut DecNumber,
    set: &DecContext,
    all: bool,
    noclamp: bool,
    dropped: &mut i32,
) -> &'a mut DecNumber {
    *dropped = 0;
    if dn.is_special() || (dn.lsu[0] & 0x01) != 0 {
        return dn;
    }
    if dn.is_zero() {
        dn.exponent = 0;
        return dn;
    }
    let mut exp = dn.exponent;
    let mut cut: u32 = 1;
    let mut up_idx: usize = 0;
    let mut d: i32 = 0;
    while d < dn.digits - 1 {
        let quot = ((dn.lsu[up_idx] as u32 >> cut) * MULTIES[cut as usize]) >> 17;
        if (dn.lsu[up_idx] as u32 - quot * DECPOWERS[cut as usize] as u32) != 0 {
            break;
        }
        if !all {
            if exp <= 0 {
                if exp == 0 {
                    break;
                }
                exp += 1;
            }
        }
        cut += 1;
        if cut > DECDPUN as u32 {
            up_idx += 1;
            cut = 1;
        }
        d += 1;
    }
    if d == 0 {
        return dn;
    }
    let mut d = d;
    if set.clamp != 0 && !noclamp {
        let maxd = set.emax - set.digits + 1 - dn.exponent;
        if maxd <= 0 {
            return dn;
        }
        if d > maxd {
            d = maxd;
        }
    }
    let units = digits_to_units(dn.digits);
    decShiftToLeast(&mut dn.lsu, units, d);
    dn.exponent += d;
    dn.digits -= d;
    *dropped = d;
    dn
}
/// Quantize or rescale operation
///
/// Quantizes lhs to have the same exponent as rhs (quant=1) or
/// rescales to the value of rhs (quant=0)
pub fn decQuantizeOp<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    set: &DecContext,
    quant: u8,
    status: &mut u32,
) -> &'a mut DecNumber {
    let inrhs = rhs;
    let reqdigits = set.digits;
    let mut residue: i32 = 0;
    let etiny = set.emin - (reqdigits - 1);
    loop {
        if ((lhs.bits | rhs.bits) & DECSPECIAL) != 0 {
            if ((lhs.bits | rhs.bits) & DECSPECIAL) & (DECSNAN | DECNAN) != 0 {
                decNaNs(res, lhs, Some(rhs), set, status);
            } else if (lhs.bits ^ rhs.bits) & DECINF != 0 {
                *status |= DEC_INVALID_OPERATION;
            } else {
                decNumberCopy(res, lhs);
            }
            break;
        }
        let reqexp = if quant != 0 { inrhs.exponent } else { decGetInt(inrhs) };
        if reqexp == BADINT || reqexp == BIGODD || reqexp == BIGEVEN || reqexp < etiny
            || reqexp > set.emax
        {
            *status |= DEC_INVALID_OPERATION;
            break;
        }
        if lhs.is_zero() {
            decNumberCopy(res, lhs);
            res.exponent = reqexp;
        } else {
            let adjust = reqexp - lhs.exponent;
            if (lhs.digits - adjust) > reqdigits {
                *status |= DEC_INVALID_OPERATION;
                break;
            }
            if adjust > 0 {
                let mut workset = set.clone();
                workset.digits = lhs.digits - adjust;
                decCopyFit(res, lhs, &workset, &mut residue, status);
                decApplyRound(res, &workset, residue, status);
                residue = 0;
                if res.exponent > reqexp {
                    if res.digits == reqdigits {
                        *status &= !(DEC_INEXACT | DEC_ROUNDED);
                        *status |= DEC_INVALID_OPERATION;
                        break;
                    }
                    res.digits = decShiftToMost(&mut res.lsu, res.digits, 1);
                    res.exponent -= 1;
                }
            } else {
                decNumberCopy(res, lhs);
                if adjust < 0 {
                    res.digits = decShiftToMost(&mut res.lsu, res.digits, -adjust);
                    res.exponent += adjust;
                }
            }
        }
        if res.exponent > set.emax - res.digits + 1 {
            *status |= DEC_INVALID_OPERATION;
            break;
        } else {
            decFinalize(res, set, &mut residue, status);
            *status &= !DEC_UNDERFLOW;
        }
        break;
    }
    res
}
/// Compute the next representable number less than rhs
///
/// Returns the largest representable number that is less than rhs
pub fn decNumberNextMinus<'a>(
    res: &'a mut DecNumber,
    rhs: &DecNumber,
    set: &DecContext,
) -> &'a mut DecNumber {
    let mut dtiny = DecNumber::new();
    let mut workset = set.clone();
    let mut status: u32 = 0;
    if (rhs.bits & (DECINF | DECNEG)) == DECINF {
        decSetMaxValue(res, set);
        return res;
    }
    decNumberZero(&mut dtiny);
    dtiny.lsu[0] = 1;
    dtiny.exponent = DECNUMMINE - 1;
    workset.round = Rounding::Floor;
    decAddOp(res, rhs, &dtiny, &workset, DECNEG, &mut status);
    status &= DEC_INVALID_OPERATION | 0x40000000;
    if status != 0 {
        let mut set_clone = set.clone();
        decStatus(res, status, &mut set_clone);
    }
    res
}
/// Compute the square root of a decimal number
///
/// Uses Newton-Raphson iteration to compute sqrt(rhs)
pub fn decNumberSquareRoot<'a>(
    res: &'a mut DecNumber,
    rhs: &DecNumber,
    set: &DecContext,
) -> &'a mut DecNumber {
    let mut workset: DecContext;
    let mut approxset: DecContext;
    let mut dzero = DecNumber::new();
    let mut residue: i32 = 0;
    let mut status: u32 = 0;
    let mut ignore: u32 = 0;
    let mut rstatus: u32;
    loop {
        if (rhs.bits & DECSPECIAL) != 0 {
            if rhs.is_infinite() {
                if rhs.is_negative() {
                    status |= DEC_INVALID_OPERATION;
                } else {
                    decNumberCopy(res, rhs);
                }
            } else {
                decNaNs(res, rhs, None, set, &mut status);
            }
            break;
        }
        let ideal = (rhs.exponent & !1) / 2;
        if rhs.is_zero() {
            decNumberCopy(res, rhs);
            res.exponent = ideal;
            decFinalize(res, set, &mut residue, &mut status);
            break;
        }
        if rhs.is_negative() {
            status |= DEC_INVALID_OPERATION;
            break;
        }
        let workp = (set.digits + 1).max(rhs.digits).max(7);
        let maxp = workp + 2;
        let mut f = DecNumber::with_capacity(d2u(rhs.digits));
        let mut a = DecNumber::with_capacity(d2u(maxp));
        let mut b = DecNumber::with_capacity(d2u(maxp));
        let mut t = DecNumber::with_capacity(d2u(3));
        decNumberCopy(&mut f, rhs);
        let mut exp = f.exponent + f.digits;
        f.exponent = -f.digits;
        workset = DecContext::default_for_kind(64);
        workset.emax = DECNUMMAXE;
        workset.emin = DECNUMMINE;
        workset.digits = workp;
        t.bits = 0;
        t.digits = 3;
        a.bits = 0;
        a.digits = 3;
        if (exp & 1) == 0 {
            t.exponent = -3;
            a.exponent = -3;
            t.lsu = vec![259];
            a.lsu = vec![819];
        } else {
            f.exponent -= 1;
            exp += 1;
            t.exponent = -4;
            a.exponent = -2;
            t.lsu = vec![819];
            a.lsu = vec![259];
        }
        let a_cloned = a.clone();
        decMultiplyOp(&mut a, &a_cloned, &f, &workset, &mut ignore);
        let a_cloned2 = a.clone();
        decAddOp(&mut a, &a_cloned2, &t, &workset, 0, &mut ignore);
        decNumberZero(&mut dzero);
        decNumberZero(&mut t);
        t.lsu[0] = 5;
        t.exponent = -1;
        workset.digits = 3;
        while workset.digits < maxp {
            workset.digits = (workset.digits * 2 - 2).min(maxp);
            decDivideOp(&mut b, &f, &a, &workset, 0x80, &mut ignore);
            let b_cloned = b.clone();
            decAddOp(&mut b, &b_cloned, &a, &workset, 0, &mut ignore);
            decMultiplyOp(&mut a, &b, &t, &workset, &mut ignore);
        }
        approxset = set.clone();
        approxset.round = Rounding::HalfEven;
        a.exponent += exp / 2;
        rstatus = 0;
        residue = 0;
        let a_cloned3 = a.clone();
        decCopyFit(&mut a, &a_cloned3, &approxset, &mut residue, &mut rstatus);
        decFinalize(&mut a, &approxset, &mut residue, &mut rstatus);
        if rstatus & DEC_OVERFLOW != 0 {
            status = rstatus;
            decNumberCopy(res, &a);
            break;
        }
        status |= rstatus & !(DEC_ROUNDED | DEC_INEXACT);
        a.exponent += exp / 2;
        decNumberCopy(res, &a);
        break;
    }
    if status != 0 {
        let mut set_clone = set.clone();
        decStatus(res, status, &mut set_clone);
    }
    res
}
/// Reduce a decimal number to its simplest form
///
/// Removes trailing zeros and adjusts exponent accordingly
pub fn decNumberReduce<'a>(
    res: &'a mut DecNumber,
    rhs: &DecNumber,
    set: &DecContext,
) -> &'a mut DecNumber {
    let mut status: u32 = 0;
    let mut residue: i32 = 0;
    let mut dropped: i32 = 0;
    loop {
        if (rhs.bits & (DECNAN | DECSNAN)) != 0 {
            decNaNs(res, rhs, None, set, &mut status);
            break;
        }
        decCopyFit(res, rhs, set, &mut residue, &mut status);
        decFinalize(res, set, &mut residue, &mut status);
        decTrim(res, set, true, false, &mut dropped);
        break;
    }
    if status != 0 {
        let mut set_clone = set.clone();
        decStatus(res, status, &mut set_clone);
    }
    res
}
/// Compute the absolute value of a decimal number
///
/// Returns |rhs| with rounding according to context
pub fn decNumberAbs<'a>(
    res: &'a mut DecNumber,
    rhs: &DecNumber,
    set: &DecContext,
) -> &'a mut DecNumber {
    let mut dzero = DecNumber::new();
    let mut status: u32 = 0;
    decNumberZero(&mut dzero);
    dzero.exponent = rhs.exponent;
    let negate = rhs.bits & DECNEG;
    decAddOp(res, &dzero, rhs, set, negate, &mut status);
    if status != 0 {
        let mut set_clone = set.clone();
        decStatus(res, status, &mut set_clone);
    }
    res
}
/// Check if a decimal number is subnormal
///
/// Returns 1 if the number is subnormal, 0 otherwise
pub fn decNumberIsSubnormal(dn: &DecNumber, set: &DecContext) -> i32 {
    if dn.is_special() {
        return 0;
    }
    if dn.is_zero() {
        return 0;
    }
    let ae = dn.exponent + dn.digits - 1;
    if ae < set.emin { 1 } else { 0 }
}
/// Compute the exclusive OR of two logical decimal numbers
///
/// Each digit must be 0 or 1, and both numbers must have exponent 0
pub fn decNumberXor<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    set: &DecContext,
) -> &'a mut DecNumber {
    if lhs.exponent != 0 || lhs.is_special() || lhs.is_negative() || rhs.exponent != 0
        || rhs.is_special() || rhs.is_negative()
    {
        let mut set_clone = set.clone();
        decStatus(res, DEC_INVALID_OPERATION, &mut set_clone);
        return res;
    }
    let units_a = d2u(lhs.digits);
    let units_b = d2u(rhs.digits);
    let units_c = d2u(set.digits);
    let msudigs = set.digits - ((units_c as i32 - 1) * DECDPUN);
    res.lsu = vec![0; units_c];
    for i in 0..units_c {
        let a = if i < units_a { lhs.lsu[i] } else { 0 };
        let b = if i < units_b { rhs.lsu[i] } else { 0 };
        res.lsu[i] = 0;
        if a != 0 || b != 0 {
            let mut av = a;
            let mut bv = b;
            for j in 0..DECDPUN as usize {
                if (av ^ bv) & 1 != 0 {
                    res.lsu[i] += DECPOWERS[j] as u16;
                }
                let da = av % 10;
                let db = bv % 10;
                if da > 1 || db > 1 {
                    let mut set_clone = set.clone();
                    decStatus(res, DEC_INVALID_OPERATION, &mut set_clone);
                    return res;
                }
                av /= 10;
                bv /= 10;
                if i == units_c - 1 && j == (msudigs - 1) as usize {
                    break;
                }
            }
        }
    }
    res.digits = decGetDigits(&res.lsu, units_c as i32);
    res.exponent = 0;
    res.bits = 0;
    res
}
const DEC_MAX_EMAX: i32 = 999999999;
const DEC_MIN_EMIN: i32 = -999999999;
/// Invert a decimal number (logical NOT for each digit)
pub fn decNumberInvert<'a>(
    res: &'a mut DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    if rhs.exponent != 0 || rhs.is_special() || rhs.is_negative() {
        decStatus(res, DEC_INVALID_OPERATION, set);
        return res;
    }
    let rhs_units = d2u(rhs.digits) as usize;
    let res_units = d2u(set.digits) as usize;
    let msudigs = set.digits - (res_units as i32 - 1) * DECDPUN;
    res.lsu.resize(res_units, 0);
    for uc_idx in 0..res_units {
        let a = if uc_idx < rhs_units && uc_idx < rhs.lsu.len() {
            rhs.lsu[uc_idx]
        } else {
            0
        };
        let mut result_unit: u16 = 0;
        let mut a_val = a;
        for i in 0..DECDPUN {
            if (!a_val) & 1 != 0 {
                result_unit += DECPOWERS[i as usize] as u16;
            }
            let digit = a_val % 10;
            a_val /= 10;
            if digit > 1 {
                decStatus(res, DEC_INVALID_OPERATION, set);
                return res;
            }
            if uc_idx == res_units - 1 && i == msudigs - 1 {
                break;
            }
        }
        res.lsu[uc_idx] = result_unit;
    }
    res.digits = decGetDigits(&res.lsu, res.lsu.len() as i32);
    res.exponent = 0;
    res.bits = 0;
    res
}
