/// Create DecNumber from i64
fn decNumberFromI64(res: &mut DecNumber, value: i64) {
    decNumberZero(res);
    if value == 0 {
        return;
    }
    let mut v = value.abs() as u64;
    res.lsu.clear();
    while v > 0 {
        res.lsu.push((v % 1000) as u16);
        v /= 1000;
    }
    if res.lsu.is_empty() {
        res.lsu.push(0);
    }
    res.digits = decGetDigits(&res.lsu, res.lsu.len() as i32);
    if value < 0 {
        res.bits |= special_bits::DECNEG;
    }
}
