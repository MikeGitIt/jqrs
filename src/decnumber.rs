/// Convert DecNumber to integral value (without inexact flag)
pub fn decNumberToIntegralValue<'a>(
    res: &'a mut DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    let mut workset = set.clone();
    workset.traps = 0;
    decNumberToIntegralExact(res, rhs, &mut workset);
    set.status |= workset.status & DEC_INVALID_OPERATION;
    res
}
/// Rescale a DecNumber
pub fn decNumberRescale<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    let mut status: u32 = 0;
    decQuantizeOp(res, lhs, rhs, set, 0, &mut status);
    if status != 0 {
        decStatus(res, status, set);
    }
    res
}
/// Byte-slice version of decBiStr for use with raw byte data.
/// This version works directly with byte slices and handles null-terminated strings.
///
/// # Arguments
/// * `targ` - The target bytes to check (null-terminated)
/// * `str1` - First reference bytes (null-terminated)
/// * `str2` - Second reference bytes (null-terminated)
///
/// # Returns
/// * `1` if all characters match either str1 or str2 up to null terminator
/// * `0` if any character fails to match both
pub fn decBiStr_bytes(targ: &[u8], str1: &[u8], str2: &[u8]) -> u8 {
    let mut idx = 0;
    loop {
        let t = targ.get(idx).copied().unwrap_or(0);
        let s1 = str1.get(idx).copied().unwrap_or(0);
        let s2 = str2.get(idx).copied().unwrap_or(0);
        if t != s1 && t != s2 {
            return 0;
        }
        if t == 0 {
            break;
        }
        idx += 1;
    }
    1
}
