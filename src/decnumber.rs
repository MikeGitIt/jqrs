/// Compare magnitudes (absolute values)
fn decCompareMag(lhs: &DecNumber, rhs: &DecNumber) -> i32 {
    if lhs.is_infinite() && rhs.is_infinite() {
        return 0;
    }
    if lhs.is_infinite() {
        return 1;
    }
    if rhs.is_infinite() {
        return -1;
    }
    let lhs_adj = lhs.exponent + lhs.digits - 1;
    let rhs_adj = rhs.exponent + rhs.digits - 1;
    if lhs_adj > rhs_adj {
        return 1;
    }
    if lhs_adj < rhs_adj {
        return -1;
    }
    decUnitCompare(&lhs.lsu, lhs.digits, &rhs.lsu, rhs.digits, 0)
}
/// Compare two unit arrays with optional shift
pub fn decUnitCompare(
    a: &[u16],
    alength: i32,
    b: &[u16],
    blength: i32,
    exp: i32,
) -> i32 {
    if exp == 0 {
        if alength > blength {
            return 1;
        }
        if alength < blength {
            return -1;
        }
        let len = alength as usize;
        for i in (0..len).rev() {
            if a[i] > b[i] {
                return 1;
            }
            if a[i] < b[i] {
                return -1;
            }
        }
        return 0;
    }
    let exp_units = d2u(exp) as i32;
    if alength > blength + exp_units {
        return 1;
    }
    if alength + 1 < blength + exp_units {
        return -1;
    }
    let need = (blength + exp_units).max(alength) + 2;
    let mut acc = vec![0u16; need as usize];
    let expunits = exp / DECDPUN;
    let exprem = exp % DECDPUN;
    let accunits = decUnitAddSub(
        a,
        alength,
        b,
        blength,
        expunits,
        &mut acc,
        -(DECPOWERS[exprem as usize] as i32),
    );
    if accunits < 0 {
        return -1;
    }
    let accunits = accunits as usize;
    for i in 0..accunits {
        if acc[i] != 0 {
            return 1;
        }
    }
    0
}
/// Next toward operation
pub fn decNumberNextToward<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    let mut status: u32 = 0;
    if lhs.is_nan() || rhs.is_nan() {
        decNaNs(res, lhs, Some(rhs), set, &mut status);
        if status != 0 {
            decStatus(res, status, set);
        }
        return res;
    }
    let result = decCompare(lhs, rhs, false);
    if result == i32::MIN {
        status |= status::DEC_INSUFFICIENT_STORAGE;
    } else if result == 0 {
        *res = lhs.clone();
        if rhs.is_negative() {
            res.bits |= special_bits::DECNEG;
        } else {
            res.bits &= !special_bits::DECNEG;
        }
    } else {
        let mut dtiny = DecNumber::new();
        dtiny.lsu[0] = 1;
        dtiny.exponent = -999999999 - 1;
        let mut workset = set.clone();
        if result < 0 {
            if lhs.is_infinite() && lhs.is_negative() {
                decSetMaxValue(res, set);
                res.bits = special_bits::DECNEG;
                return res;
            }
            workset.round = Rounding::Ceiling;
            decAddOp(res, lhs, &dtiny, &workset, 0, &mut status);
        } else {
            if lhs.is_infinite() && !lhs.is_negative() {
                decSetMaxValue(res, set);
                return res;
            }
            workset.round = Rounding::Floor;
            decAddOp(res, lhs, &dtiny, &workset, special_bits::DECNEG, &mut status);
        }
        if decNumberIsNormal(res, set) {
            status = 0;
        }
    }
    if status != 0 {
        decStatus(res, status, set);
    }
    res
}
/// Natural logarithm
pub fn decNumberLn<'a>(
    res: &'a mut DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    let mut status: u32 = 0;
    if decCheckMath(rhs, set, &mut status) == 0 {
        decLnOp(res, rhs, set, &mut status);
    }
    if status != 0 {
        decStatus(res, status, set);
    }
    res
}
/// Create DecNumber from f64 (approximate)
fn dec_from_f64(res: &mut DecNumber, value: f64, _set: &DecContext) {
    decNumberZero(res);
    if value == 0.0 {
        return;
    }
    let negative = value < 0.0;
    let abs_val = value.abs();
    let s = format!("{:.15e}", abs_val);
    let parts: Vec<&str> = s.split('e').collect();
    if parts.len() != 2 {
        return;
    }
    let mantissa = parts[0].replace('.', "");
    let exp: i32 = parts[1].parse().unwrap_or(0);
    let digits: Vec<u8> = mantissa
        .chars()
        .filter_map(|c| c.to_digit(10).map(|d| d as u8))
        .collect();
    if digits.is_empty() {
        return;
    }
    res.lsu.clear();
    let mut i = digits.len();
    while i > 0 {
        let start = if i >= 3 { i - 3 } else { 0 };
        let mut unit: u16 = 0;
        let mut mult = 1;
        for j in (start..i).rev() {
            unit += (digits[j] as u16) * mult;
            mult *= 10;
        }
        res.lsu.push(unit);
        i = start;
    }
    res.lsu.reverse();
    res.digits = digits.len() as i32;
    res.exponent = exp - (res.digits - 1);
    if negative {
        res.bits |= special_bits::DECNEG;
    }
}
/// Set subnormal handling
pub fn decSetSubnormal(
    dn: &mut DecNumber,
    set: &DecContext,
    residue: &mut i32,
    status: &mut u32,
) {
    let etiny = set.emin - (set.digits - 1);
    if dn.is_zero() {
        if dn.exponent < etiny {
            dn.exponent = etiny;
            *status |= status::DEC_CLAMPED;
        }
        return;
    }
    *status |= status::DEC_SUBNORMAL;
    let adjust = etiny - dn.exponent;
    if adjust <= 0 {
        if (*status & status::DEC_INEXACT) != 0 {
            *status |= status::DEC_UNDERFLOW;
        }
        return;
    }
    let mut workset = set.clone();
    workset.digits = dn.digits - adjust;
    workset.emin -= adjust;
    let lsu_copy = dn.lsu.clone();
    decSetCoeff(dn, &workset, &lsu_copy, dn.digits, residue, status);
    decApplyRound(dn, &workset, *residue, status);
    if (*status & status::DEC_INEXACT) != 0 {
        *status |= status::DEC_UNDERFLOW;
    }
    if dn.exponent > etiny {
        dn.digits = decShiftToMost(&mut dn.lsu, dn.digits, 1);
        dn.exponent -= 1;
    }
    if dn.is_zero() {
        *status |= status::DEC_CLAMPED;
    }
}
/// Apply rounding to a number
pub fn decApplyRound(
    dn: &mut DecNumber,
    set: &DecContext,
    residue: i32,
    status: &mut u32,
) {
    if residue == 0 {
        return;
    }
    let bump: i32;
    match set.round {
        Rounding::ZeroFiveUp => {
            let lsd5 = (dn.lsu[0] % 5) as i32;
            if residue < 0 && lsd5 != 1 {
                bump = -1;
            } else if residue > 0 && lsd5 == 0 {
                bump = 1;
            } else {
                bump = 0;
            }
        }
        Rounding::Down => {
            bump = if residue < 0 { -1 } else { 0 };
        }
        Rounding::HalfDown => {
            bump = if residue > 5 { 1 } else { 0 };
        }
        Rounding::HalfEven => {
            if residue > 5 {
                bump = 1;
            } else if residue == 5 {
                bump = if (dn.lsu[0] & 0x01) != 0 { 1 } else { 0 };
            } else {
                bump = 0;
            }
        }
        Rounding::HalfUp => {
            bump = if residue >= 5 { 1 } else { 0 };
        }
        Rounding::Up => {
            bump = if residue > 0 { 1 } else { 0 };
        }
        Rounding::Ceiling => {
            if dec_number_is_negative(dn) {
                bump = if residue < 0 { -1 } else { 0 };
            } else {
                bump = if residue > 0 { 1 } else { 0 };
            }
        }
        Rounding::Floor => {
            if !dec_number_is_negative(dn) {
                bump = if residue < 0 { -1 } else { 0 };
            } else {
                bump = if residue > 0 { 1 } else { 0 };
            }
        }
        Rounding::Max => {
            bump = 0;
        }
    }
    if bump == 0 {
        return;
    }
    let units = d2u(dn.digits) as usize;
    if bump > 0 {
        let mut count = dn.digits;
        for i in 0..units {
            if count <= DECDPUN {
                if dn.lsu[i] != (DECPOWERS[count as usize] - 1) as u16 {
                    dn.lsu[i] += 1;
                    return;
                }
                dn.lsu[i] = DECPOWERS[(count - 1) as usize] as u16;
                for j in (0..i).rev() {
                    dn.lsu[j] = 0;
                }
                dn.exponent += 1;
                if dn.exponent + dn.digits > set.emax + 1 {
                    decSetOverflow(dn, set, status);
                }
                return;
            }
            if dn.lsu[i] != 999 {
                dn.lsu[i] += 1;
                return;
            }
            dn.lsu[i] = 0;
            count -= DECDPUN;
        }
    } else {
        let mut count = dn.digits;
        for i in 0..units {
            if count <= DECDPUN {
                let min_val = DECPOWERS[(count - 1) as usize] as u16;
                if dn.lsu[i] != min_val {
                    dn.lsu[i] -= 1;
                    return;
                }
                dn.lsu[i] = (DECPOWERS[count as usize] - 1) as u16;
                for j in (0..i).rev() {
                    dn.lsu[j] = (DECPOWERS[DECDPUN as usize] - 1) as u16;
                }
                dn.exponent -= 1;
                if dn.exponent + 1 == set.emin - set.digits + 1 {
                    if count == 1 && dn.digits == 1 {
                        dn.lsu[i] = 0;
                    } else {
                        dn.lsu[i] = (DECPOWERS[(count - 1) as usize] - 1) as u16;
                        dn.digits -= 1;
                    }
                    dn.exponent += 1;
                    *status |= DEC_UNDERFLOW | DEC_SUBNORMAL | DEC_INEXACT | DEC_ROUNDED;
                }
                return;
            }
            if dn.lsu[i] != 0 {
                dn.lsu[i] -= 1;
                return;
            }
            dn.lsu[i] = (DECPOWERS[DECDPUN as usize] - 1) as u16;
            count -= DECDPUN;
        }
    }
}
/// Check if number is normal
fn decNumberIsNormal(dn: &DecNumber, set: &DecContext) -> bool {
    if dn.is_special() || dn.is_zero() {
        return false;
    }
    let adj_exp = dn.exponent + dn.digits - 1;
    adj_exp >= set.emin && adj_exp <= set.emax
}
/// Copy sign from one number to another
pub fn decNumberCopySign<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
) -> &'a mut DecNumber {
    *res = lhs.clone();
    res.bits = (res.bits & !special_bits::DECNEG) | (rhs.bits & special_bits::DECNEG);
    res
}
