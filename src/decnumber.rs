/// Quantize operation (stub)
pub fn decNumberQuantize<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    let mut status: u32 = 0;
    if dec_number_is_nan(lhs) || dec_number_is_nan(rhs) {
        decNaNs(res, lhs, Some(rhs), set, &mut status);
    } else if dec_number_is_infinite(lhs) != dec_number_is_infinite(rhs) {
        status |= DEC_INVALID_OPERATION;
        decStatus(res, status, set);
    } else if dec_number_is_infinite(lhs) {
        decNumberCopy(res, lhs);
    } else {
        decNumberCopy(res, lhs);
        let exp_diff = res.exponent - rhs.exponent;
        if exp_diff > 0 {
            res.ensure_capacity((res.digits + exp_diff) as usize);
            res.digits = decShiftToMost(&mut res.lsu, res.digits, exp_diff);
        } else if exp_diff < 0 {
            let units = d2u(res.digits);
            decShiftToLeast(&mut res.lsu, units as i32, -exp_diff);
            res.digits = (res.digits + exp_diff).max(1);
        }
        res.exponent = rhs.exponent;
        if res.digits > set.digits {
            status |= DEC_INVALID_OPERATION;
        }
    }
    if status != 0 {
        decStatus(res, status, set);
    }
    res
}
/// Copy with negated sign
pub fn decNumberCopyNegate<'a>(res: &'a mut DecNumber, rhs: &DecNumber) -> &'a mut DecNumber {
    decNumberCopy(res, rhs);
    res.bits ^= DECNEG;
    res
}
/// Power operation
pub fn decNumberPower<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    set: &DecContext,
) -> &'a mut DecNumber {
    let req_digits = set.digits;
    let mut status = 0u32;
    let mut residue = 0i32;
    loop {
        if lhs.is_nan() || rhs.is_nan() {
            decNaNs(res, lhs, Some(rhs), set, &mut status);
            break;
        }
        if rhs.is_infinite() {
            let rhs_neg = rhs.is_negative();
            if lhs.is_negative() && !lhs.is_zero() {
                status |= DEC_INVALID_OPERATION;
            } else {
                let mut dn_one = DecNumber::new();
                dn_one.lsu[0] = 1;
                let cmp_result = decCompare(lhs, &dn_one, false);
                decNumberZero(res);
                if cmp_result < 0 {
                    if rhs_neg {
                        res.bits |= DECINF;
                    }
                } else if cmp_result == 0 {
                    let shift = set.digits - 1;
                    res.lsu[0] = 1;
                    res.digits = decShiftToMost(&mut res.lsu, 1, shift);
                    res.exponent = -shift;
                    status |= DEC_INEXACT | DEC_ROUNDED;
                } else {
                    if !rhs_neg {
                        res.bits |= DECINF;
                    }
                }
            }
            break;
        }
        let n = decGetInt(rhs);
        let rhs_int = n != i32::MIN;
        let use_int = rhs_int && n != i32::MIN + 2 && n != i32::MIN + 3;
        let is_odd_int = (n & 1) != 0;
        let mut bits: u8 = 0;
        if lhs.is_negative() && is_odd_int {
            bits = DECNEG;
        }
        if lhs.is_infinite() {
            decNumberZero(res);
            if n == 0 {
                res.lsu[0] = 1;
            } else {
                if !rhs_int && lhs.is_negative() {
                    status |= DEC_INVALID_OPERATION;
                    break;
                }
                if !rhs.is_negative() {
                    bits |= DECINF;
                }
                res.bits = bits;
            }
            break;
        }
        if lhs.is_zero() {
            if n == 0 {
                status |= DEC_INVALID_OPERATION;
            } else {
                if rhs.is_negative() {
                    bits |= DECINF;
                }
                decNumberZero(res);
                res.bits = bits;
            }
            break;
        }
        if !use_int {
            if lhs.is_negative() {
                status |= DEC_INVALID_OPERATION;
                break;
            }
            if decCheckMath(lhs, set, &mut status) != 0 || decCheckMath(rhs, set, &mut status) != 0
            {
                break;
            }
            status |= DEC_INVALID_OPERATION;
        } else {
            if n == 0 {
                decNumberZero(res);
                res.lsu[0] = 1;
                break;
            }
            let mut exp = if n < 0 { -n } else { n };
            let mut aset = set.clone();
            aset.round = Rounding::HalfEven;
            aset.digits = req_digits + (rhs.digits + rhs.exponent) + 2;
            if aset.digits > DECNUMMAXP {
                status |= DEC_INVALID_OPERATION;
                break;
            }
            let mut dac = DecNumber::with_capacity(d2u(aset.digits) as usize);
            dac.lsu[0] = 1;
            dac.digits = 1;
            let base = if n < 0 {
                let mut inv = DecNumber::with_capacity(d2u(aset.digits) as usize);
                let one = {
                    let mut o = DecNumber::new();
                    o.lsu[0] = 1;
                    o
                };
                decDivideOp(&mut inv, &one, lhs, &aset, DIVIDE, &mut status);
                inv
            } else {
                lhs.clone()
            };
            let mut seen_bit = false;
            for i in 0..31 {
                if (status & (DEC_OVERFLOW | DEC_UNDERFLOW)) != 0 {
                    if (status & DEC_OVERFLOW) != 0 || dac.is_zero() {
                        break;
                    }
                }
                let bit = ((exp << i) >> 30) & 1;
                if bit == 1 {
                    seen_bit = true;
                    let temp = dac.clone();
                    decMultiplyOp(&mut dac, &temp, &base, &aset, &mut status);
                }
                if i == 30 {
                    break;
                }
                if !seen_bit {
                    continue;
                }
                let temp = dac.clone();
                decMultiplyOp(&mut dac, &temp, &temp, &aset, &mut status);
            }
            if (status & (DEC_OVERFLOW | DEC_UNDERFLOW)) != 0 {
                dac.bits = (dac.bits & !DECNEG) | bits;
                decFinalize(&mut dac, set, &mut residue, &mut status);
                decNumberCopy(res, &dac);
                break;
            }
            decCopyFit(res, &dac, set, &mut residue, &mut status);
            decFinalize(res, set, &mut residue, &mut status);
        }
        break;
    }
    if status != 0 {
        let set_mut = &mut set.clone();
        decStatus(res, status, set_mut);
    }
    res
}
/// Set BCD digits in a DecNumber
pub fn decNumberSetBCD<'a>(dn: &'a mut DecNumber, bcd: &[u8], n: u32) -> &'a mut DecNumber {
    if n == 0 {
        decNumberZero(dn);
        return dn;
    }
    let units = d2u(n as i32) as usize;
    dn.lsu.clear();
    dn.lsu.resize(units, 0);
    let mut cut = (n as i32) - ((units as i32 - 1) * 3);
    let mut up = units - 1;
    let mut ub = 0usize;
    loop {
        dn.lsu[up] = 0;
        while cut > 0 && ub < bcd.len() {
            dn.lsu[up] = dn.lsu[up] * 10 + bcd[ub] as u16;
            ub += 1;
            cut -= 1;
        }
        cut = 3;
        if up == 0 {
            break;
        }
        up -= 1;
    }
    dn.digits = n as i32;
    dn
}
