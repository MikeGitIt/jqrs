/// Convert a DecNumber to i32
pub fn decNumberToInt32(dn: &DecNumber, set: &mut DecContext) -> i32 {
    if (dn.bits & DECSPECIAL) != 0 || dn.digits > 10 || dn.exponent != 0 {
        decContextSetStatus(set, DEC_INVALID_OPERATION);
        return 0;
    }
    let mut hi: u32 = 0;
    let lo: u32;
    let first_unit = dn.lsu[0] as u32;
    hi = first_unit / 10;
    lo = first_unit % 10;
    let mut up_idx = 1;
    let mut d = 3;
    while d < dn.digits {
        if up_idx < dn.lsu.len() {
            hi += dn.lsu[up_idx] as u32 * DECPOWERS[(d - 1) as usize] as u32;
        }
        up_idx += 1;
        d += 3;
    }
    if hi > 214748364 || (hi == 214748364 && lo > 7) {
        if (dn.bits & DECNEG) != 0 && hi == 214748364 && lo == 8 {
            return i32::MIN;
        }
        decContextSetStatus(set, DEC_INVALID_OPERATION);
        return 0;
    }
    let result = ((hi << 1) + (hi << 3) + lo) as i32;
    if (dn.bits & DECNEG) != 0 { -result } else { result }
}
/// Convert a DecNumber to u32
pub fn decNumberToUInt32(dn: &DecNumber, set: &mut DecContext) -> u32 {
    if (dn.bits & DECSPECIAL) != 0 || dn.digits > 10 || dn.exponent != 0 {
        decContextSetStatus(set, DEC_INVALID_OPERATION);
        return 0;
    }
    if (dn.bits & DECNEG) != 0 && !dn.is_zero() {
        decContextSetStatus(set, DEC_INVALID_OPERATION);
        return 0;
    }
    let mut hi: u32 = 0;
    let lo: u32;
    let first_unit = dn.lsu[0] as u32;
    hi = first_unit / 10;
    lo = first_unit % 10;
    let mut up_idx = 1;
    let mut d = 3;
    while d < dn.digits {
        if up_idx < dn.lsu.len() {
            hi += dn.lsu[up_idx] as u32 * DECPOWERS[(d - 1) as usize] as u32;
        }
        up_idx += 1;
        d += 3;
    }
    if hi > 429496729 || (hi == 429496729 && lo > 5) {
        decContextSetStatus(set, DEC_INVALID_OPERATION);
        return 0;
    }
    ((hi << 1) + (hi << 3)) + lo
}
/// Format number with exponent notation
fn format_with_exponent(result: &mut String, digits: &[u8], pre: i32, e: i32) {
    let mut idx = 0;
    if pre > 0 {
        for _ in 0..pre {
            if idx < digits.len() {
                result.push((b'0' + digits[idx]) as char);
                idx += 1;
            } else {
                result.push('0');
            }
        }
        if idx < digits.len() {
            result.push('.');
            while idx < digits.len() {
                result.push((b'0' + digits[idx]) as char);
                idx += 1;
            }
        }
    } else {
        result.push('0');
        result.push('.');
        for _ in pre..0 {
            result.push('0');
        }
        for d in digits {
            result.push((b'0' + d) as char);
        }
    }
    if e != 0 {
        result.push('E');
        if e >= 0 {
            result.push('+');
        }
        result.push_str(&e.to_string());
    }
}
