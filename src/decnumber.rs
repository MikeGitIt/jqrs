fn dec_number_is_zero(dn: &DecNumber) -> bool {
    dn.lsu[0] == 0 && dn.digits == 1 && (dn.bits & DECSPECIAL) == 0
}
fn dec_number_is_negative(dn: &DecNumber) -> bool {
    (dn.bits & DECNEG) != 0
}
fn dec_number_is_nan(dn: &DecNumber) -> bool {
    (dn.bits & (DECNAN | DECSNAN)) != 0
}
fn dec_number_is_infinite(dn: &DecNumber) -> bool {
    (dn.bits & DECINF) != 0
}
/// Initialize context with default values
pub fn decContextDefault(context: &mut DecContext, kind: i32) -> &mut DecContext {
    match kind {
        32 => {
            context.digits = 7;
            context.emax = 96;
            context.emin = -95;
        }
        64 => {
            context.digits = 16;
            context.emax = 384;
            context.emin = -383;
        }
        128 => {
            context.digits = 34;
            context.emax = 6144;
            context.emin = -6143;
        }
        _ => {
            context.digits = 9;
            context.emax = 999999999;
            context.emin = -999999999;
        }
    }
    context.round = Rounding::HalfEven;
    context.traps = 0;
    context.status = 0;
    context.clamp = 0;
    context
}
/// Decapitate (remove most significant digits)
fn decDecap(dn: &mut DecNumber, drop: i32) {
    if drop >= dn.digits {
        dn.lsu[0] = 0;
        dn.digits = 1;
        return;
    }
    let new_digits = dn.digits - drop;
    let new_units = d2u(new_digits) as usize;
    let old_units = d2u(dn.digits) as usize;
    for i in new_units..old_units {
        if i < dn.lsu.len() {
            dn.lsu[i] = 0;
        }
    }
    let partial = new_digits % DECDPUN;
    if partial != 0 && new_units > 0 {
        let mask = DECPOWERS[partial as usize] as u16;
        if new_units <= dn.lsu.len() {
            dn.lsu[new_units - 1] %= mask;
        }
    }
    dn.digits = new_digits;
}
/// Set overflow result
fn decSetOverflow(dn: &mut DecNumber, set: &DecContext, status: &mut u32) {
    *status |= DEC_OVERFLOW | DEC_INEXACT | DEC_ROUNDED;
    let neg = dec_number_is_negative(dn);
    match set.round {
        Rounding::Ceiling if neg => {}
        Rounding::Floor if !neg => {}
        Rounding::Down => {}
        _ => {
            dn.bits = if neg { DECNEG | DECINF } else { DECINF };
            dn.digits = 1;
            dn.lsu.clear();
            dn.lsu.push(0);
            return;
        }
    }
    dn.digits = set.digits;
    dn.exponent = set.emax - set.digits + 1;
    let units = d2u(set.digits) as usize;
    dn.lsu.clear();
    for _ in 0..(units - 1) {
        dn.lsu.push(999);
    }
    let remaining = ((set.digits - 1) % DECDPUN) + 1;
    dn.lsu.push((DECPOWERS[remaining as usize] - 1) as u16);
}
/// Compute base-10 logarithm
pub fn decNumberLog10<'a>(
    res: &'a mut DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    let mut status: u32 = 0;
    let mut ignore: u32 = 0;
    let mut bufa = DecNumber::with_capacity(36 + 2);
    let mut bufb = DecNumber::with_capacity(36 + 2);
    let mut bufw = DecNumber::with_capacity(10);
    let mut aset = DecContext::default();
    if decCheckMath(rhs, set, &mut status) == 0 {
        loop {
            decContextDefault(&mut aset, DEC_INIT_DECIMAL128);
            if (rhs.bits & (DECNEG | DECSPECIAL)) == 0 && !dec_number_is_zero(rhs) {
                let mut residue: i32 = 0;
                let mut copystat: u32 = 0;
                aset.digits = 1;
                decCopyFit(&mut bufw, rhs, &aset, &mut residue, &mut copystat);
                if (copystat & DEC_INEXACT) == 0 && bufw.lsu[0] == 1 {
                    let bufw_exp = bufw.exponent;
                    decNumberFromInt32(&mut bufw, bufw_exp);
                    residue = 0;
                    decCopyFit(res, &bufw, set, &mut residue, &mut status);
                    decFinalize(res, set, &mut residue, &mut status);
                    break;
                }
            }
            let t = 6;
            let p = (rhs.digits + t).max(set.digits) + 3;
            bufa.ensure_capacity(p as usize);
            aset.digits = p;
            aset.emax = 999999;
            aset.emin = -999999;
            aset.clamp = 0;
            decLnOp(&mut bufa, rhs, &aset, &mut status);
            if (status
                & (DEC_CONVERSION_SYNTAX | DEC_DIVISION_BY_ZERO | DEC_DIVISION_IMPOSSIBLE
                    | DEC_INSUFFICIENT_STORAGE | DEC_INVALID_OPERATION | DEC_OVERFLOW))
                != 0 && (status & DEC_LOST_DIGITS) == 0
            {
                break;
            }
            if (bufa.bits & DECSPECIAL) != 0 || dec_number_is_zero(&bufa) {
                decNumberCopy(res, &bufa);
                break;
            }
            let p2 = set.digits + 3;
            bufb.ensure_capacity(p2 as usize);
            decNumberZero(&mut bufw);
            bufw.lsu[0] = 10;
            bufw.digits = 2;
            aset.digits = p2;
            decLnOp(&mut bufb, &bufw, &aset, &mut ignore);
            aset.digits = set.digits;
            decDivideOp(res, &bufa, &bufb, &aset, DIVIDE, &mut status);
            break;
        }
    }
    if status != 0 {
        decStatus(res, status, set);
    }
    res
}
/// Shift digits
pub fn decNumberShift<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    let mut status: u32 = 0;
    if dec_number_is_nan(lhs) || dec_number_is_nan(rhs) {
        decNaNs(res, lhs, Some(rhs), set, &mut status);
    } else if dec_number_is_infinite(rhs) || rhs.exponent != 0 {
        status = DEC_INVALID_OPERATION;
    } else {
        let shift = decGetInt(rhs);
        if shift == i32::MIN || shift.abs() > set.digits {
            status = DEC_INVALID_OPERATION;
        } else {
            decNumberCopy(res, lhs);
            if shift != 0 && !dec_number_is_infinite(res) {
                if shift > 0 {
                    if shift == set.digits {
                        res.lsu[0] = 0;
                        res.digits = 1;
                    } else {
                        if res.digits + shift > set.digits {
                            decDecap(res, res.digits + shift - set.digits);
                        }
                        if res.digits > 1 || res.lsu[0] != 0 {
                            res.ensure_capacity((res.digits + shift) as usize);
                            res.digits = decShiftToMost(&mut res.lsu, res.digits, shift);
                        }
                    }
                } else {
                    let neg_shift = -shift;
                    if neg_shift >= res.digits {
                        res.lsu[0] = 0;
                        res.digits = 1;
                    } else {
                        let units = d2u(res.digits);
                        decShiftToLeast(&mut res.lsu, units as i32, neg_shift);
                        res.digits -= neg_shift;
                    }
                }
            }
        }
    }
    if status != 0 {
        decStatus(res, status, set);
    }
    res
}
