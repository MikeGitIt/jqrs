impl DecContext {
    /// Create a new context with default settings for a given precision kind
    pub fn default_context(kind: i32) -> Self {
        let mut ctx = Self::default();
        if kind == DEC_INIT_DECIMAL64 {
            ctx.digits = 16;
            ctx.emax = 384;
            ctx.emin = -383;
        }
        ctx
    }
    /// Set a status flag and trigger trap if enabled
    pub fn set_status(&mut self, status: u32) {
        self.status |= status;
    }
    pub fn new(digits: i32) -> Self {
        DecContext {
            digits,
            ..Default::default()
        }
    }
    /// Create a default context for a specific precision kind
    pub fn default_for_kind(kind: i32) -> Self {
        match kind {
            64 => {
                DecContext {
                    digits: 16,
                    emax: 384,
                    emin: -383,
                    round: Rounding::HalfEven,
                    traps: 0,
                    status: 0,
                    clamp: 1,
                }
            }
            128 => {
                DecContext {
                    digits: 34,
                    emax: 6144,
                    emin: -6143,
                    round: Rounding::HalfEven,
                    traps: 0,
                    status: 0,
                    clamp: 1,
                }
            }
            _ => DecContext::default(),
        }
    }
}
impl DecNumber {
    /// Check if the number is zero
    pub fn is_zero(&self) -> bool {
        self.lsu.first() == Some(&0) && self.digits == 1 && (self.bits & DECSPECIAL) == 0
    }
    /// Check if the number is infinite
    pub fn is_infinite(&self) -> bool {
        (self.bits & DECINF) != 0
    }
    /// Check if the number is NaN (quiet or signaling)
    pub fn is_nan(&self) -> bool {
        (self.bits & (DECNAN | DECSNAN)) != 0
    }
    /// Check if the number is a signaling NaN
    pub fn is_snan(&self) -> bool {
        (self.bits & DECSNAN) != 0
    }
    /// Get the number of units needed for the given digit count
    fn units_for_digits(digits: i32) -> i32 {
        if digits <= 49 {
            D2UTABLE[digits as usize]
        } else {
            (digits + DECDPUN - 1) / DECDPUN
        }
    }
    /// Get the number of digits in the most significant unit
    fn msu_digits(&self) -> i32 {
        self.digits - (Self::units_for_digits(self.digits) - 1) * DECDPUN
    }
    pub fn with_capacity(units: usize) -> Self {
        DecNumber {
            digits: 1,
            exponent: 0,
            bits: 0,
            lsu: vec![0; units.max(1)],
        }
    }
    pub fn is_qnan(&self) -> bool {
        (self.bits & DECNAN) != 0
    }
    /// Ensure the lsu vector has enough capacity
    fn ensure_capacity(&mut self, units: usize) {
        if self.lsu.len() < units {
            self.lsu.resize(units, 0);
        }
    }
}
