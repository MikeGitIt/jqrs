/// Logical AND of two decimal numbers
pub fn decNumberAnd<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    if lhs.exponent != 0 || lhs.is_special() || lhs.is_negative() || rhs.exponent != 0
        || rhs.is_special() || rhs.is_negative()
    {
        decStatus(res, DEC_INVALID_OPERATION, set);
        return res;
    }
    let lhs_units = digits_to_units(lhs.digits) as usize;
    let rhs_units = digits_to_units(rhs.digits) as usize;
    let res_units = digits_to_units(set.digits) as usize;
    let msudigs = set.digits - ((res_units as i32 - 1) * DECDPUN);
    res.lsu.resize(res_units, 0);
    for i in 0..res_units {
        let a = if i < lhs_units { lhs.lsu[i] } else { 0 };
        let b = if i < rhs_units { rhs.lsu[i] } else { 0 };
        res.lsu[i] = 0;
        if a | b != 0 {
            let mut out: u16 = 0;
            let mut av = a;
            let mut bv = b;
            for j in 0..DECDPUN {
                if (av & bv & 1) != 0 {
                    out += DECPOWERS[j as usize] as u16;
                }
                let ja = av % 10;
                av /= 10;
                let jb = bv % 10;
                bv /= 10;
                if ja > 1 || jb > 1 {
                    decStatus(res, DEC_INVALID_OPERATION, set);
                    return res;
                }
                if i == res_units - 1 && j == msudigs - 1 {
                    break;
                }
            }
            res.lsu[i] = out;
        }
    }
    res.digits = decGetDigits(&res.lsu, res_units as i32);
    res.exponent = 0;
    res.bits = 0;
    res
}
