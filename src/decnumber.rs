/// Log base 10 of a number (returns adjusted exponent)
pub fn decNumberLogB<'a>(
    res: &'a mut DecNumber,
    rhs: &DecNumber,
    set: &DecContext,
) -> &'a mut DecNumber {
    let mut status = 0u32;
    if rhs.is_nan() {
        decNaNs(res, rhs, None, set, &mut status);
    } else if rhs.is_infinite() {
        decNumberCopyAbs(res, rhs);
    } else if rhs.is_zero() {
        decNumberZero(res);
        res.bits = DECNEG | DECINF;
        status |= DEC_DIVISION_BY_ZERO;
    } else {
        let ae = rhs.exponent + rhs.digits - 1;
        if set.digits >= 10 {
            decNumberFromInt32(res, ae);
        } else {
            let mut t = DecNumber::with_capacity(4);
            decNumberFromInt32(&mut t, ae);
            decNumberPlus(res, &t, set);
        }
    }
    if status != 0 {
        let set_mut = &mut set.clone();
        decStatus(res, status, set_mut);
    }
    res
}
