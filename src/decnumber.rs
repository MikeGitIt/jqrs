/// Copy absolute value
pub fn decNumberCopyAbs<'a>(dest: &'a mut DecNumber, src: &DecNumber) -> &'a mut DecNumber {
    decNumberCopy(dest, src);
    dest.bits &= !DECNEG;
    dest
}
/// Check math operand validity
fn decCheckMath(rhs: &DecNumber, set: &DecContext, status: &mut u32) -> u32 {
    let save = *status;
    if set.digits > DECNUMMAXP || set.emax > DECNUMMAXP || -set.emin > DECNUMMAXP {
        *status |= DEC_INVALID_CONTEXT;
    } else if (rhs.digits > DECNUMMAXP || rhs.exponent + rhs.digits > DECNUMMAXP + 1
        || rhs.exponent + rhs.digits < 2 * (1 - DECNUMMAXP)) && !rhs.is_zero()
    {
        *status |= DEC_INVALID_OPERATION;
    }
    if *status != save { 1 } else { 0 }
}
/// Add or subtract decimal units
pub fn decUnitAddSub(
    a: &[u16],
    alength: i32,
    b: &[u16],
    blength: i32,
    bshift: i32,
    c: &mut Vec<u16>,
    m: i32,
) -> i32 {
    let alength = alength as usize;
    let blength = blength as usize;
    let bshift = bshift as usize;
    let max_len = (alength + bshift).max(blength + bshift) + 1;
    c.resize(max_len, 0);
    let mut carry: i32 = 0;
    let mut ci = 0usize;
    let ai_start;
    if bshift > 0 {
        for i in 0..bshift {
            if i < alength {
                c[ci] = a[i];
            } else {
                c[ci] = 0;
            }
            ci += 1;
        }
        ai_start = bshift;
    } else {
        ai_start = 0;
    }
    let mut ai = ai_start;
    let mut bi = 0usize;
    let min_end = (alength).min(blength + bshift);
    let max_end = (alength).max(blength + bshift);
    while ci < min_end {
        if ai < alength {
            carry += a[ai] as i32;
            ai += 1;
        }
        if bi < blength {
            carry += (b[bi] as i32) * m;
            bi += 1;
        }
        if (carry as u32) <= DECDPUNMAX as u32 {
            c[ci] = carry as u16;
            carry = 0;
        } else if carry >= 0 {
            let est = (((carry as u32) >> 3) * 16777) >> 21;
            c[ci] = (carry as u32 - est * (DECDPUNMAX as u32 + 1)) as u16;
            carry = est as i32;
            if c[ci] >= DECDPUNMAX + 1 {
                carry += 1;
                c[ci] -= DECDPUNMAX + 1;
            }
        } else {
            let adjusted = carry + (DECDPUNMAX as i32 + 1) * (DECDPUNMAX as i32 + 1);
            let est = (((adjusted as u32) >> 3) * 16777) >> 21;
            c[ci] = (adjusted as u32 - est * (DECDPUNMAX as u32 + 1)) as u16;
            carry = est as i32 - (DECDPUNMAX as i32 + 1);
            if c[ci] >= DECDPUNMAX + 1 {
                carry += 1;
                c[ci] -= DECDPUNMAX + 1;
            }
        }
        ci += 1;
    }
    while ci < max_end {
        if ai < alength {
            carry += a[ai] as i32;
            ai += 1;
        } else if bi < blength {
            carry += (b[bi] as i32) * m;
            bi += 1;
        }
        if (carry as u32) <= DECDPUNMAX as u32 {
            c[ci] = carry as u16;
            carry = 0;
        } else if carry >= 0 {
            let est = (((carry as u32) >> 3) * 16777) >> 21;
            c[ci] = (carry as u32 - est * (DECDPUNMAX as u32 + 1)) as u16;
            carry = est as i32;
            if c[ci] >= DECDPUNMAX + 1 {
                carry += 1;
                c[ci] -= DECDPUNMAX + 1;
            }
        } else {
            let adjusted = carry + (DECDPUNMAX as i32 + 1) * (DECDPUNMAX as i32 + 1);
            let est = (((adjusted as u32) >> 3) * 16777) >> 21;
            c[ci] = (adjusted as u32 - est * (DECDPUNMAX as u32 + 1)) as u16;
            carry = est as i32 - (DECDPUNMAX as i32 + 1);
            if c[ci] >= DECDPUNMAX + 1 {
                carry += 1;
                c[ci] -= DECDPUNMAX + 1;
            }
        }
        ci += 1;
    }
    if carry == 0 {
        return ci as i32;
    }
    if carry > 0 {
        c[ci] = carry as u16;
        ci += 1;
        return ci as i32;
    }
    let mut add = 1i32;
    for i in 0..ci {
        add = (DECDPUNMAX as i32) + add - (c[i] as i32);
        if add <= DECDPUNMAX as i32 {
            c[i] = add as u16;
            add = 0;
        } else {
            c[i] = 0;
            add = 1;
        }
    }
    let correction = add - carry - 1;
    if correction != 0 {
        c[ci] = correction as u16;
        ci += 1;
    }
    -(ci as i32)
}
/// Set coefficient with rounding
pub fn decSetCoeff(
    dn: &mut DecNumber,
    set: &DecContext,
    lsu: &[u16],
    len: i32,
    residue: &mut i32,
    status: &mut u32,
) {
    let discard = len - set.digits;
    if discard <= 0 {
        let count = d2u(len) as usize;
        dn.lsu.clear();
        dn.lsu.extend_from_slice(&lsu[..count.min(lsu.len())]);
        dn.digits = len;
        if *residue != 0 {
            *status |= DEC_INEXACT | DEC_ROUNDED;
        }
        return;
    }
    dn.exponent += discard;
    *status |= DEC_ROUNDED;
    if *residue > 1 {
        *residue = 1;
    }
    if discard > len {
        if *residue <= 0 {
            for i in 0..d2u(len) as usize {
                if i < lsu.len() && lsu[i] != 0 {
                    *residue = 1;
                    break;
                }
            }
        }
        if *residue != 0 {
            *status |= DEC_INEXACT;
        }
        dn.lsu.clear();
        dn.lsu.push(0);
        dn.digits = 1;
        return;
    }
    let mut count = 0i32;
    let mut up_idx = 0usize;
    loop {
        count += DECDPUN;
        if count >= discard {
            break;
        }
        if up_idx < lsu.len() && lsu[up_idx] != 0 {
            *residue = 1;
        }
        up_idx += 1;
    }
    let cut = (discard - (count - DECDPUN) - 1) as usize;
    if cut == (DECDPUN - 1) as usize {
        let half = (DECPOWERS[DECDPUN as usize] >> 1) as u16;
        if up_idx < lsu.len() {
            if lsu[up_idx] >= half {
                if lsu[up_idx] > half {
                    *residue = 7;
                } else {
                    *residue += 5;
                }
            } else if lsu[up_idx] != 0 {
                *residue = 3;
            }
        }
        if set.digits <= 0 {
            dn.lsu.clear();
            dn.lsu.push(0);
            dn.digits = 1;
        } else {
            dn.digits = set.digits;
            dn.lsu.clear();
            up_idx += 1;
            let target_units = d2u(set.digits) as usize;
            for i in 0..target_units {
                if up_idx + i < lsu.len() {
                    dn.lsu.push(lsu[up_idx + i]);
                } else {
                    dn.lsu.push(0);
                }
            }
        }
    } else {
        let cut_u32 = cut as u32;
        let quot = if cut == 0 {
            lsu[up_idx] as u32
        } else {
            let q = ((lsu[up_idx] as u32) >> cut_u32) * MULTIES[cut] >> 17;
            let rem = lsu[up_idx] as u32 - q * DECPOWERS[cut] as u32;
            if rem != 0 {
                *residue = 1;
            }
            q
        };
        let discard1 = quot % 10;
        let quot = quot / 10;
        *residue += RESMAP[discard1 as usize];
        if set.digits <= 0 {
            dn.lsu.clear();
            dn.lsu.push(0);
            dn.digits = 1;
        } else {
            dn.digits = set.digits;
            dn.lsu.clear();
            let mut current_quot = quot;
            let cut_plus = cut + 1;
            let mut remaining = set.digits;
            loop {
                dn.lsu.push(current_quot as u16);
                remaining -= (DECDPUN - cut_plus as i32);
                if remaining <= 0 {
                    break;
                }
                up_idx += 1;
                if up_idx >= lsu.len() {
                    break;
                }
                let next_quot = ((lsu[up_idx] as u32) >> cut_u32) * MULTIES[cut] >> 17;
                let rem = lsu[up_idx] as u32 - next_quot * DECPOWERS[cut] as u32;
                let last_idx = dn.lsu.len() - 1;
                dn.lsu[last_idx] = (dn.lsu[last_idx] as u32
                    + rem * DECPOWERS[DECDPUN as usize - cut_plus] as u32) as u16;
                current_quot = next_quot;
                remaining -= cut_plus as i32;
                if remaining <= 0 {
                    break;
                }
            }
        }
    }
    if *residue != 0 {
        *status |= DEC_INEXACT;
    }
}
/// Plus operation (unary +)
pub fn decNumberPlus<'a>(
    res: &'a mut DecNumber,
    rhs: &DecNumber,
    set: &DecContext,
) -> &'a mut DecNumber {
    let mut status = 0u32;
    let mut residue = 0i32;
    decCopyFit(res, rhs, set, &mut residue, &mut status);
    res.bits &= !DECNEG;
    decFinalize(res, set, &mut residue, &mut status);
    if status != 0 {
        let set_mut = &mut set.clone();
        decStatus(res, status, set_mut);
    }
    res
}
