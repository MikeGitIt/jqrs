/// Get number of digits in unit array
pub fn decGetDigits(uar: &[u16], len: i32) -> i32 {
    if len <= 0 {
        return 1;
    }
    let mut digits = (len - 1) * 3 + 1;
    for i in (0..len as usize).rev() {
        if i >= uar.len() {
            continue;
        }
        let val = uar[i];
        if val == 0 {
            if digits == 1 {
                break;
            }
            digits -= 3;
            continue;
        }
        if val < 10 {
            break;
        }
        digits += 1;
        if val < 100 {
            break;
        }
        digits += 1;
        break;
    }
    digits
}
/// Get integer value from a decimal number
///
/// Returns the integer value of dn if it can be represented as an i32,
/// or special values for overflow/truncation cases
pub fn decGetInt(dn: &DecNumber) -> i32 {
    let ilength = dn.digits + dn.exponent;
    let neg = dn.is_negative();
    if dn.is_zero() {
        return 0;
    }
    let mut up_idx = 0;
    let mut the_int: i32 = 0;
    let mut got: i32;
    if dn.exponent >= 0 {
        got = dn.exponent;
    } else {
        let mut count = -dn.exponent;
        while count >= DECDPUN && up_idx < dn.lsu.len() {
            if dn.lsu[up_idx] != 0 {
                return BADINT;
            }
            count -= DECDPUN;
            up_idx += 1;
        }
        if count == 0 {
            got = 0;
        } else {
            if up_idx >= dn.lsu.len() {
                return BADINT;
            }
            let unit = dn.lsu[up_idx] as u32;
            the_int = ((unit >> count) * MULTIES[count as usize] >> 17) as i32;
            let rem = unit as i32 - the_int * DECPOWERS[count as usize];
            if rem != 0 {
                return BADINT;
            }
            got = DECDPUN - count;
            up_idx += 1;
        }
    }
    if got == 0 && up_idx < dn.lsu.len() {
        the_int = dn.lsu[up_idx] as i32;
        got += DECDPUN;
        up_idx += 1;
    }
    if ilength < 11 {
        let save = the_int;
        while got < ilength && up_idx < dn.lsu.len() {
            the_int += (dn.lsu[up_idx] as i32) * DECPOWERS[got as usize];
            got += DECDPUN;
            up_idx += 1;
        }
        if ilength == 10 {
            if up_idx > 0
                && the_int / DECPOWERS[(got - DECDPUN) as usize]
                    != dn.lsu[up_idx - 1] as i32
            {
                the_int = save;
            } else if neg && the_int > 1999999997 {
                the_int = save;
            } else if !neg && the_int > 999999999 {
                the_int = save;
            } else {
                if neg {
                    return -the_int;
                }
                return the_int;
            }
        } else {
            if neg {
                return -the_int;
            }
            return the_int;
        }
    }
    if the_int & 1 != 0 { BIGODD } else { BIGEVEN }
}
/// Create DecNumber from i32
pub fn decNumberFromInt32(dn: &mut DecNumber, value: i32) -> &mut DecNumber {
    let mut val = value;
    let neg = val < 0;
    if neg {
        val = -val;
    }
    dn.exponent = 0;
    dn.bits = if neg { DECNEG } else { 0 };
    dn.lsu.clear();
    if val == 0 {
        dn.digits = 1;
        dn.lsu.push(0);
    } else {
        let mut digits = 0;
        let mut temp = val as u32;
        while temp > 0 {
            dn.lsu.push((temp % 1000) as u16);
            temp /= 1000;
            digits
                += if temp > 0 || dn.lsu.last().unwrap() >= &100 {
                    3
                } else if *dn.lsu.last().unwrap() >= 10 {
                    if digits == 0 { 2 } else { 3 }
                } else {
                    if digits == 0 { 1 } else { 3 }
                };
        }
        dn.digits = 0;
        let mut v = val as u32;
        while v > 0 {
            dn.digits += 1;
            v /= 10;
        }
    }
    dn
}
/// Convert a u32 to a DecNumber
pub fn decNumberFromUInt32(dn: &mut DecNumber, uin: u32) -> &mut DecNumber {
    decNumberZero(dn);
    if uin == 0 {
        return dn;
    }
    let mut value = uin;
    dn.lsu.clear();
    while value > 0 {
        dn.lsu.push((value % 1000) as u16);
        value /= 1000;
    }
    dn.digits = decGetDigits(&dn.lsu, dn.lsu.len() as i32);
    dn
}
/// Parse a decimal number from a string
pub fn decNumberFromString<'a>(
    dn: &'a mut DecNumber,
    chars: &str,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    let mut exponent: i32 = 0;
    let mut bits: u8 = 0;
    let mut d: i32 = 0;
    let mut dotpos: Option<usize> = None;
    let mut status: u32 = 0;
    let bytes = chars.as_bytes();
    let mut cfirst: usize = 0;
    let mut last: Option<usize> = None;
    let mut c: usize = 0;
    'parse: loop {
        while c < bytes.len() {
            let ch = bytes[c];
            if ch >= b'0' && ch <= b'9' {
                last = Some(c);
                d += 1;
                c += 1;
                continue;
            }
            if ch == b'.' && dotpos.is_none() {
                dotpos = Some(c);
                if c == cfirst {
                    cfirst += 1;
                }
                c += 1;
                continue;
            }
            if c == 0 {
                if ch == b'-' {
                    cfirst = 1;
                    bits = DECNEG;
                    c += 1;
                    continue;
                }
                if ch == b'+' {
                    cfirst = 1;
                    c += 1;
                    continue;
                }
            }
            break;
        }
        if last.is_none() {
            status = DEC_CONVERSION_SYNTAX;
            if c >= bytes.len() {
                break 'parse;
            }
            if dotpos.is_some() {
                break 'parse;
            }
            decNumberZero(dn);
            let remaining = &chars[c..];
            if decBiStr(remaining, "infinity", "INFINITY") != 0
                || decBiStr(remaining, "inf", "INF") != 0
            {
                dn.bits = bits | DECINF;
                status = 0;
                break 'parse;
            }
            dn.bits = bits | DECNAN;
            let mut nc = c;
            if nc < bytes.len() && (bytes[nc] == b's' || bytes[nc] == b'S') {
                nc += 1;
                dn.bits = bits | DECSNAN;
            }
            if nc >= bytes.len() || (bytes[nc] != b'n' && bytes[nc] != b'N') {
                break 'parse;
            }
            nc += 1;
            if nc >= bytes.len() || (bytes[nc] != b'a' && bytes[nc] != b'A') {
                break 'parse;
            }
            nc += 1;
            if nc >= bytes.len() || (bytes[nc] != b'n' && bytes[nc] != b'N') {
                break 'parse;
            }
            nc += 1;
            cfirst = nc;
            while cfirst < bytes.len() && bytes[cfirst] == b'0' {
                cfirst += 1;
            }
            if cfirst >= bytes.len() {
                status = 0;
                break 'parse;
            }
            d = 0;
            c = cfirst;
            while c < bytes.len() {
                if bytes[c] < b'0' || bytes[c] > b'9' {
                    break;
                }
                last = Some(c);
                c += 1;
                d += 1;
            }
            if c < bytes.len() {
                break 'parse;
            }
            if d > set.digits - 1 {
                if set.clamp != 0 {
                    break 'parse;
                }
                if d > set.digits {
                    break 'parse;
                }
            }
            status = 0;
            bits = dn.bits;
        } else if c < bytes.len() {
            let ch = bytes[c];
            if ch != b'e' && ch != b'E' {
                status = DEC_CONVERSION_SYNTAX;
                break 'parse;
            }
            c += 1;
            let mut nege = false;
            if c < bytes.len() {
                if bytes[c] == b'-' {
                    nege = true;
                    c += 1;
                } else if bytes[c] == b'+' {
                    c += 1;
                }
            }
            if c >= bytes.len() {
                status = DEC_CONVERSION_SYNTAX;
                break 'parse;
            }
            while c < bytes.len() - 1 && bytes[c] == b'0' {
                c += 1;
            }
            let firstexp = c;
            let mut expa: u32 = 0;
            while c < bytes.len() {
                if bytes[c] < b'0' || bytes[c] > b'9' {
                    break;
                }
                expa = expa * 10 + (bytes[c] - b'0') as u32;
                c += 1;
            }
            if c < bytes.len() {
                status = DEC_CONVERSION_SYNTAX;
                break 'parse;
            }
            if c >= firstexp + 10 {
                expa = 999999999 * 2;
            }
            exponent = expa as i32;
            if nege {
                exponent = -exponent;
            }
            status = 0;
        }
        let last_idx = last.unwrap();
        let mut cfirst = cfirst;
        while cfirst < last_idx {
            let ch = bytes[cfirst];
            if ch == b'.' {
                cfirst += 1;
                continue;
            }
            if ch != b'0' {
                break;
            }
            d -= 1;
            cfirst += 1;
        }
        if let Some(dp) = dotpos {
            if dp < last_idx {
                exponent -= (last_idx - dp) as i32;
            }
        }
        let units = digits_to_units(d);
        dn.lsu.resize(units as usize, 0);
        let mut out: u32 = 0;
        let mut up_idx = (units - 1) as usize;
        let mut cut = d - (up_idx as i32) * DECDPUN;
        let mut ci = cfirst;
        loop {
            let ch = bytes[ci];
            if ch == b'.' {
                ci += 1;
                continue;
            }
            out = out * 10 + (ch - b'0') as u32;
            if ci == last_idx {
                break;
            }
            cut -= 1;
            if cut > 0 {
                ci += 1;
                continue;
            }
            dn.lsu[up_idx] = out as u16;
            if up_idx > 0 {
                up_idx -= 1;
            }
            cut = DECDPUN;
            out = 0;
            ci += 1;
        }
        dn.lsu[up_idx] = out as u16;
        dn.bits = bits;
        dn.exponent = exponent;
        dn.digits = d;
        if d > set.digits {
            let mut residue: i32 = 0;
            decSetCoeff(dn, set, &dn.lsu.clone(), d, &mut residue, &mut status);
            decFinalize(dn, set, &mut residue, &mut status);
        } else {
            if (dn.exponent - 1 < set.emin - dn.digits)
                || (dn.exponent - 1 > set.emax - set.digits)
            {
                let mut residue: i32 = 0;
                decFinalize(dn, set, &mut residue, &mut status);
            }
        }
        break;
    }
    if status != 0 {
        decStatus(dn, status, set);
    }
    dn
}
/// Handle NaN operands
fn decNaNs<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: Option<&DecNumber>,
    set: &DecContext,
    status: &mut u32,
) -> &'a mut DecNumber {
    let mut chosen = lhs;
    if (lhs.bits & DECSNAN) != 0 {
        *status |= DEC_INVALID_OPERATION | DEC_INEXACT;
    } else if let Some(r) = rhs {
        if (r.bits & DECSNAN) != 0 {
            chosen = r;
            *status |= DEC_INVALID_OPERATION | DEC_INEXACT;
        } else if (lhs.bits & DECNAN) == 0 {
            chosen = r;
        }
    }
    if chosen.digits <= set.digits {
        decNumberCopy(res, chosen);
    } else {
        res.bits = chosen.bits;
        let units = d2u(set.digits) as usize;
        res.lsu.clear();
        res.lsu.extend_from_slice(&chosen.lsu[..units.min(chosen.lsu.len())]);
        res.digits = units as i32 * DECDPUN;
        if res.digits > set.digits {
            decDecap(res, res.digits - set.digits);
        }
    }
    res.bits &= !DECSNAN;
    res.bits |= DECNAN;
    res.exponent = 0;
    res
}
/// Set status and handle special values
fn decStatus(dn: &mut DecNumber, status: u32, set: &mut DecContext) {
    let mut status = status;
    if status
        & (DEC_INVALID_OPERATION | DEC_DIVISION_BY_ZERO | DEC_OVERFLOW | DEC_UNDERFLOW
            | DEC_CLAMPED | DEC_SUBNORMAL) != 0
    {
        if status & DEC_NAN_STATUS != 0 {
            status &= !DEC_NAN_STATUS;
        } else {
            decNumberZero(dn);
            dn.bits = DECNAN;
        }
    }
    decContextSetStatus(set, status);
}
/// Compare two decimal numbers
pub fn decCompare(lhs: &DecNumber, rhs: &DecNumber, abs_compare: bool) -> i32 {
    let lhs_zero = lhs.is_zero();
    let rhs_zero = rhs.is_zero();
    if lhs_zero && rhs_zero {
        return 0;
    }
    if !abs_compare {
        let lhs_neg = lhs.is_negative();
        let rhs_neg = rhs.is_negative();
        if lhs_neg != rhs_neg {
            if lhs_zero {
                return if rhs_neg { 1 } else { -1 };
            }
            if rhs_zero {
                return if lhs_neg { -1 } else { 1 };
            }
            return if lhs_neg { -1 } else { 1 };
        }
        if lhs_zero {
            return if rhs_neg { 1 } else { -1 };
        }
        if rhs_zero {
            return if lhs_neg { -1 } else { 1 };
        }
    } else {
        if lhs_zero {
            return -1;
        }
        if rhs_zero {
            return 1;
        }
    }
    let lhs_adj = lhs.exponent + lhs.digits - 1;
    let rhs_adj = rhs.exponent + rhs.digits - 1;
    let mut result = match lhs_adj.cmp(&rhs_adj) {
        Ordering::Less => -1,
        Ordering::Greater => 1,
        Ordering::Equal => {
            let lhs_units = digits_to_units(lhs.digits);
            let rhs_units = digits_to_units(rhs.digits);
            let shift = lhs.exponent - rhs.exponent;
            decUnitCompare(&lhs.lsu, lhs_units, &rhs.lsu, rhs_units, shift)
        }
    };
    if !abs_compare && lhs.is_negative() {
        result = -result;
    }
    result
}
/// Compare operation for decimal numbers
pub fn decCompareOp<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
    op: u8,
    status: &mut u32,
) -> &'a mut DecNumber {
    let mut result: i32 = 0;
    'compare: loop {
        if op == COMPTOTAL {
            if lhs.is_negative() && !rhs.is_negative() {
                result = -1;
                break 'compare;
            }
            if !lhs.is_negative() && rhs.is_negative() {
                result = 1;
                break 'compare;
            }
        }
        let merged = (lhs.bits | rhs.bits) & (DECSNAN | DECNAN);
        if merged != 0 {
            if op == COMPARE {} else if op == COMPSIGNAL {
                *status |= DEC_INVALID_OPERATION | 0x40000000;
            } else if op == COMPTOTAL {
                if !lhs.is_nan() {
                    result = -1;
                } else if !rhs.is_nan() {
                    result = 1;
                } else if lhs.is_snan() && rhs.is_qnan() {
                    result = -1;
                } else if lhs.is_qnan() && rhs.is_snan() {
                    result = 1;
                } else {
                    let lhs_units = digits_to_units(lhs.digits);
                    let rhs_units = digits_to_units(rhs.digits);
                    result = decUnitCompare(&lhs.lsu, lhs_units, &rhs.lsu, rhs_units, 0);
                }
                if lhs.is_negative() {
                    result = -result;
                }
                break 'compare;
            } else if (merged & DECSNAN) != 0 {} else {
                if !lhs.is_nan() || !rhs.is_nan() {
                    if lhs.is_qnan() {
                        result = -1;
                    } else {
                        result = 1;
                    }
                    break 'compare;
                }
            }
            decNaNs(res, lhs, Some(rhs), set, status);
            break 'compare;
        }
        if op == COMPMAXMAG || op == COMPMINMAG {
            result = decCompare(lhs, rhs, true);
        } else {
            result = decCompare(lhs, rhs, false);
        }
        break;
    }
    if result == i32::MIN {
        *status |= DEC_INSUFFICIENT_STORAGE;
    } else {
        if op == COMPARE || op == COMPSIGNAL || op == COMPTOTAL {
            if op == COMPTOTAL && result == 0 {
                if lhs.exponent != rhs.exponent {
                    if lhs.exponent < rhs.exponent {
                        result = -1;
                    } else {
                        result = 1;
                    }
                    if lhs.is_negative() {
                        result = -result;
                    }
                }
            }
            decNumberZero(res);
            if result != 0 {
                res.lsu[0] = 1;
                if result < 0 {
                    res.bits = DECNEG;
                }
            }
        } else if op != COMPNAN {
            let mut residue: i32 = 0;
            if result == 0 {
                let slhs = lhs.is_negative();
                let srhs = rhs.is_negative();
                if slhs != srhs {
                    result = if slhs { -1 } else { 1 };
                } else if slhs && srhs {
                    result = if lhs.exponent < rhs.exponent { 1 } else { -1 };
                } else {
                    result = if lhs.exponent > rhs.exponent { 1 } else { -1 };
                }
            }
            if op == COMPMIN || op == COMPMINMAG {
                result = -result;
            }
            let choice = if result > 0 { lhs } else { rhs };
            decCopyFit(res, choice, set, &mut residue, status);
            decFinalize(res, set, &mut residue, status);
        }
    }
    res
}
/// Add operation for DecNumbers
///
/// # Arguments
/// * `res` - Result DecNumber
/// * `lhs` - Left operand
/// * `rhs` - Right operand
/// * `set` - Decimal context
/// * `negate` - If true, subtract instead of add
/// * `status` - Status flags
///
/// # Returns
/// Reference to the result
pub fn decAddOp<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    set: &DecContext,
    negate: u8,
    status: &mut u32,
) -> &'a mut DecNumber {
    let diffsign = ((lhs.bits ^ rhs.bits ^ negate) & special_bits::DECNEG) != 0;
    if lhs.is_special() || rhs.is_special() {
        if lhs.is_nan() || rhs.is_nan() {
            decNaNs(res, lhs, Some(rhs), set, status);
            return res;
        }
        if lhs.is_infinite() {
            if rhs.is_infinite() && diffsign {
                *status |= status::DEC_INVALID_OPERATION;
                decNumberZero(res);
                res.bits = special_bits::DECNAN;
                return res;
            }
            let bits = lhs.bits & special_bits::DECNEG;
            decNumberZero(res);
            res.bits = bits | special_bits::DECINF;
            return res;
        }
        let bits = (rhs.bits ^ negate) & special_bits::DECNEG;
        decNumberZero(res);
        res.bits = bits | special_bits::DECINF;
        return res;
    }
    if lhs.is_zero() {
        let mut residue = 0i32;
        decCopyFit(res, rhs, set, &mut residue, status);
        res.bits ^= negate;
        if res.is_zero() && diffsign {
            if set.round == Rounding::Floor {
                res.bits = special_bits::DECNEG;
            } else {
                res.bits = 0;
            }
        }
        decFinalize(res, set, &mut residue, status);
        return res;
    }
    if rhs.is_zero() {
        let mut residue = 0i32;
        decCopyFit(res, lhs, set, &mut residue, status);
        decFinalize(res, set, &mut residue, status);
        return res;
    }
    let padding = rhs.exponent - lhs.exponent;
    if padding == 0 && rhs.digits <= 3 && lhs.digits <= set.digits
        && rhs.digits <= set.digits
    {
        let partial = lhs.lsu[0] as i32;
        if !diffsign {
            let sum = partial + rhs.lsu[0] as i32;
            if sum <= 999 && (lhs.digits >= 3 || sum < DECPOWERS[lhs.digits as usize]) {
                if res as *const _ != lhs as *const _ {
                    *res = lhs.clone();
                }
                res.lsu[0] = sum as u16;
                return res;
            }
        } else {
            let diff = partial - rhs.lsu[0] as i32;
            if diff > 0 {
                if res as *const _ != lhs as *const _ {
                    *res = lhs.clone();
                }
                res.lsu[0] = diff as u16;
                res.digits = decGetDigits(&res.lsu, res.lsu.len() as i32);
                return res;
            }
        }
    }
    let (actual_lhs, actual_rhs, bits, rhsshift, mult) = if padding < 0 {
        let mult = if diffsign { -1 } else { 1 };
        (rhs, lhs, rhs.bits ^ negate, (-padding + DECDPUN - 1) / DECDPUN - 1, mult)
    } else if padding > 0 {
        let mult = if diffsign { -1 } else { 1 };
        (lhs, rhs, lhs.bits, (padding + DECDPUN - 1) / DECDPUN - 1, mult)
    } else {
        let mult = if diffsign { -1 } else { 1 };
        (lhs, rhs, lhs.bits, 0, mult)
    };
    let max_digits = actual_lhs.digits.max(actual_rhs.digits + padding.abs());
    let acc_units = (max_digits as usize + DECDPUN as usize - 1) / DECDPUN as usize + 1;
    let mut acc: Vec<u16> = vec![0; acc_units];
    let result_digits = decUnitAddSub(
        &actual_lhs.lsu,
        d2utable(actual_lhs.digits),
        &actual_rhs.lsu,
        d2utable(actual_rhs.digits),
        rhsshift,
        &mut acc,
        mult,
    );
    res.bits = bits & special_bits::DECNEG;
    res.exponent = actual_lhs.exponent.min(actual_rhs.exponent);
    if result_digits < 0 {
        res.digits = -result_digits * DECDPUN;
        res.bits ^= special_bits::DECNEG;
    } else {
        res.digits = result_digits * DECDPUN;
    }
    res.lsu = acc;
    res.digits = decGetDigits(&res.lsu, res.lsu.len() as i32);
    let mut residue = 0i32;
    decFinalize(res, set, &mut residue, status);
    if res.is_zero() && diffsign && (*status & status::DEC_INEXACT) == 0 {
        if set.round == Rounding::Floor {
            res.bits |= special_bits::DECNEG;
        } else {
            res.bits &= !special_bits::DECNEG;
        }
    }
    res
}
/// Convert DecNumber to i64 if possible
fn dec_to_i64(dn: &DecNumber) -> Option<i64> {
    if dn.is_special() {
        return None;
    }
    let mut value: i64 = 0;
    let mut multiplier: i64 = 1;
    for &unit in &dn.lsu {
        value += (unit as i64) * multiplier;
        multiplier *= 1000;
    }
    if dn.exponent > 0 {
        for _ in 0..dn.exponent {
            value = value.checked_mul(10)?;
        }
    } else if dn.exponent < 0 {
        for _ in 0..(-dn.exponent) {
            value /= 10;
        }
    }
    if dn.is_negative() {
        value = -value;
    }
    Some(value)
}
/// Multiply operation (internal)
pub fn decMultiplyOp<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    set: &DecContext,
    status: &mut u32,
) -> &'a mut DecNumber {
    let bits = ((lhs.bits ^ rhs.bits) & DECNEG);
    if (lhs.bits | rhs.bits) & DECSPECIAL != 0 {
        if (lhs.bits | rhs.bits) & (DECSNAN | DECNAN) != 0 {
            decNaNs(res, lhs, Some(rhs), set, status);
            return res;
        }
        if (!lhs.is_infinite() && lhs.is_zero()) || (!rhs.is_infinite() && rhs.is_zero())
        {
            *status |= DEC_INVALID_OPERATION;
            return res;
        }
        decNumberZero(res);
        res.bits = bits | DECINF;
        return res;
    }
    let (lhs, rhs) = if lhs.digits < rhs.digits { (rhs, lhs) } else { (lhs, rhs) };
    let l_units = d2u(lhs.digits) as usize;
    let r_units = d2u(rhs.digits) as usize;
    let acc_units = l_units + r_units;
    let mut acc = vec![0u16; acc_units + 1];
    for i in 0..r_units {
        if i >= rhs.lsu.len() || rhs.lsu[i] == 0 {
            continue;
        }
        let r_val = rhs.lsu[i] as u32;
        let mut carry = 0u32;
        for j in 0..l_units {
            let l_val = if j < lhs.lsu.len() { lhs.lsu[j] as u32 } else { 0 };
            let idx = i + j;
            let prod = l_val * r_val + acc[idx] as u32 + carry;
            acc[idx] = (prod % 1000) as u16;
            carry = prod / 1000;
        }
        let mut idx = i + l_units;
        while carry > 0 && idx < acc.len() {
            let sum = acc[idx] as u32 + carry;
            acc[idx] = (sum % 1000) as u16;
            carry = sum / 1000;
            idx += 1;
        }
    }
    let mut actual_units = acc_units;
    while actual_units > 1 && acc[actual_units - 1] == 0 {
        actual_units -= 1;
    }
    res.bits = bits;
    res.digits = decGetDigits(&acc, actual_units as i32);
    let mut exponent = lhs.exponent + rhs.exponent;
    if lhs.exponent < 0 && rhs.exponent < 0 && exponent > 0 {
        exponent = -2 * DECNUMMAXP;
    }
    res.exponent = exponent;
    let mut residue = 0i32;
    decSetCoeff(res, set, &acc, res.digits, &mut residue, status);
    decFinalize(res, set, &mut residue, status);
    res
}
/// Divide operation (internal)
pub fn decDivideOp<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    set: &DecContext,
    op: u8,
    status: &mut u32,
) -> &'a mut DecNumber {
    let bits = (lhs.bits ^ rhs.bits) & DECNEG;
    loop {
        if (lhs.bits | rhs.bits) & DECSPECIAL != 0 {
            if (lhs.bits | rhs.bits) & (DECSNAN | DECNAN) != 0 {
                decNaNs(res, lhs, Some(rhs), set, status);
                break;
            }
            if lhs.is_infinite() {
                if rhs.is_infinite() || (op & (REMAINDER | REMNEAR)) != 0 {
                    *status |= DEC_INVALID_OPERATION;
                    break;
                }
                decNumberZero(res);
                res.bits = bits | DECINF;
                break;
            } else {
                let mut residue = 0i32;
                if (op & (REMAINDER | REMNEAR)) != 0 {
                    decCopyFit(res, lhs, set, &mut residue, status);
                } else {
                    decNumberZero(res);
                    res.bits = bits;
                    if (op & DIVIDE) != 0 {
                        res.exponent = set.emin - set.digits + 1;
                        *status |= DEC_CLAMPED;
                    }
                }
                decFinalize(res, set, &mut residue, status);
                break;
            }
        }
        if rhs.is_zero() {
            if lhs.is_zero() {
                decNumberZero(res);
                *status |= DEC_DIVISION_UNDEFINED;
            } else {
                decNumberZero(res);
                if (op & (REMAINDER | REMNEAR)) != 0 {
                    *status |= DEC_INVALID_OPERATION;
                } else {
                    *status |= DEC_DIVISION_BY_ZERO;
                    res.bits = bits | DECINF;
                }
            }
            break;
        }
        if lhs.is_zero() {
            if (op & DIVIDE) != 0 {
                let mut residue = 0i32;
                let exponent = lhs.exponent - rhs.exponent;
                decNumberCopy(res, lhs);
                res.bits = bits;
                res.exponent = exponent;
                decFinalize(res, set, &mut residue, status);
            } else if (op & DIVIDEINT) != 0 {
                decNumberZero(res);
                res.bits = bits;
            } else {
                let exponent = rhs.exponent;
                decNumberCopy(res, lhs);
                if exponent < res.exponent {
                    res.exponent = exponent;
                }
            }
            break;
        }
        let req_digits = set.digits;
        let l_digits = lhs.digits;
        let r_digits = rhs.digits;
        let mut exponent = (lhs.exponent + l_digits) - (rhs.exponent + r_digits);
        let acc_length = d2u(req_digits + 3) as usize;
        let mut acc = vec![0u16; acc_length];
        let mut acc_digits = 0i32;
        let mut var1: Vec<u16> = lhs.lsu.clone();
        while var1.len() < (d2u(l_digits) as usize + 10) {
            var1.push(0);
        }
        let mut result_digits = Vec::new();
        let divisor_val = {
            let mut val = 0u64;
            for i in (0..rhs.lsu.len()).rev() {
                val = val * 1000 + rhs.lsu[i] as u64;
            }
            val
        };
        if divisor_val > 0 {
            let mut dividend_val = 0u64;
            for i in (0..var1.len()).rev() {
                dividend_val = dividend_val * 1000 + var1[i] as u64;
            }
            let quotient = dividend_val / divisor_val;
            let remainder = dividend_val % divisor_val;
            let mut q = quotient;
            while q > 0 || acc.is_empty() {
                let idx = result_digits.len().min(acc.len() - 1);
                acc[idx] = (q % 1000) as u16;
                result_digits.push((q % 1000) as u16);
                q /= 1000;
            }
            acc_digits = decGetDigits(&acc, result_digits.len() as i32);
            if (op & (REMAINDER | REMNEAR)) != 0 {
                decNumberZero(res);
                if remainder > 0 {
                    let mut r = remainder;
                    res.lsu.clear();
                    while r > 0 {
                        res.lsu.push((r % 1000) as u16);
                        r /= 1000;
                    }
                    res.digits = decGetDigits(&res.lsu, res.lsu.len() as i32);
                }
                res.exponent = lhs.exponent.min(rhs.exponent);
                res.bits = lhs.bits & DECNEG;
                break;
            }
        } else {
            acc[0] = 0;
            acc_digits = 1;
        }
        res.exponent = exponent;
        res.bits = bits;
        let mut residue = 0i32;
        decSetCoeff(res, set, &acc, acc_digits, &mut residue, status);
        decFinalize(res, set, &mut residue, status);
        break;
    }
    res
}
/// Helper to convert DecNumber to f64
fn dec_to_f64(dn: &DecNumber) -> f64 {
    if dn.is_special() {
        if dn.is_infinite() {
            return if dn.is_negative() { f64::NEG_INFINITY } else { f64::INFINITY };
        }
        return f64::NAN;
    }
    let mut result = 0.0_f64;
    let mut mult = 1.0_f64;
    for unit in &dn.lsu {
        result += *unit as f64 * mult;
        mult *= 1000.0;
    }
    result *= 10.0_f64.powi(dn.exponent);
    if dn.is_negative() { -result } else { result }
}
/// Helper to convert f64 to DecNumber
fn f64_to_dec(dn: &mut DecNumber, value: f64, _set: &DecContext) {
    decNumberZero(dn);
    if value.is_nan() {
        dn.bits = DECNAN;
        return;
    }
    if value.is_infinite() {
        dn.bits = DECINF;
        if value < 0.0 {
            dn.bits |= DECNEG;
        }
        return;
    }
    if value == 0.0 {
        return;
    }
    let negative = value < 0.0;
    let abs_val = value.abs();
    let s = format!("{:.15e}", abs_val);
    let mut set_clone = _set.clone();
    decNumberFromString(dn, &s, &mut set_clone);
    if negative {
        dn.bits |= DECNEG;
    }
}
/// Copy and fit to precision
fn decCopyFit(
    dest: &mut DecNumber,
    src: &DecNumber,
    set: &DecContext,
    residue: &mut i32,
    status: &mut u32,
) {
    *dest = src.clone();
    if dest.digits > set.digits {
        *status |= status::DEC_ROUNDED;
        *residue = 1;
        let excess = dest.digits - set.digits;
        dest.exponent += excess;
        dest.digits = set.digits;
        let units_needed = d2utable(set.digits) as usize;
        if dest.lsu.len() > units_needed {
            let shift = dest.lsu.len() - units_needed;
            dest.lsu = dest.lsu[shift..].to_vec();
        }
    }
}
/// Finalize a DecNumber (apply rounding and check for over/underflow)
pub fn decFinalize(
    dn: &mut DecNumber,
    set: &DecContext,
    residue: &mut i32,
    status: &mut u32,
) {
    let tinyexp = set.emin - dn.digits + 1;
    if dn.exponent <= tinyexp {
        if dn.exponent < tinyexp {
            decSetSubnormal(dn, set, residue, status);
            return;
        }
        let mut nmin = DecNumber::new();
        nmin.lsu[0] = 1;
        nmin.exponent = set.emin;
        let comp = decCompare(dn, &nmin, true);
        if comp == i32::MIN {
            *status |= DEC_INSUFFICIENT_STORAGE;
            return;
        }
        if *residue < 0 && comp == 0 {
            decApplyRound(dn, set, *residue, status);
            decSetSubnormal(dn, set, residue, status);
            return;
        }
    }
    if *residue != 0 {
        decApplyRound(dn, set, *residue, status);
    }
    if dn.exponent > set.emax - set.digits + 1 {
        if dn.exponent > set.emax - dn.digits + 1 {
            decSetOverflow(dn, set, status);
            return;
        }
    }
    if set.clamp == 0 {
        return;
    }
    let shift = dn.exponent - (set.emax - set.digits + 1);
    if shift <= 0 {
        return;
    }
    if !dn.is_zero() {
        dn.digits = decShiftToMost(&mut dn.lsu, dn.digits, shift);
    }
    dn.exponent -= shift;
    *status |= DEC_CLAMPED;
}
/// Set the maximum value for a given context
fn decSetMaxValue(res: &mut DecNumber, set: &DecContext) {
    let units = d2u(set.digits);
    res.lsu = vec![0; units];
    res.digits = set.digits;
    res.exponent = set.emax - set.digits + 1;
    res.bits = 0;
    let full_units = (set.digits / DECDPUN) as usize;
    let remaining = (set.digits % DECDPUN) as usize;
    for i in 0..full_units {
        res.lsu[i] = 999;
    }
    if remaining > 0 {
        res.lsu[full_units] = (DECPOWERS[remaining] - 1) as u16;
    }
}
/// Shift array of units to least significant
pub fn decShiftToLeast(uar: &mut [u16], units: i32, shift: i32) -> i32 {
    if shift <= 0 || units <= 0 {
        return units * DECDPUN;
    }
    let cut = (shift % DECDPUN) as u32;
    let drop_units = (shift / DECDPUN) as usize;
    if drop_units >= units as usize {
        for unit in uar.iter_mut() {
            *unit = 0;
        }
        return 0;
    }
    if cut == 0 {
        for i in 0..(units as usize - drop_units) {
            uar[i] = uar[i + drop_units];
        }
        for i in (units as usize - drop_units)..units as usize {
            uar[i] = 0;
        }
    } else {
        let power = DECPOWERS[cut as usize] as u32;
        let inv_power = DECPOWERS[(DECDPUN as u32 - cut) as usize] as u32;
        for i in 0..(units as usize - drop_units) {
            let src_idx = i + drop_units;
            let next_idx = src_idx + 1;
            let current = uar.get(src_idx).copied().unwrap_or(0) as u32;
            let next = if next_idx < units as usize { uar[next_idx] as u32 } else { 0 };
            uar[i] = ((current / power) + (next % power) * inv_power) as u16;
        }
        for i in (units as usize - drop_units)..units as usize {
            if i < uar.len() {
                uar[i] = 0;
            }
        }
    }
    (units - shift / DECDPUN) * DECDPUN - (shift % DECDPUN)
}
/// Shift to most significant position
pub fn decShiftToMost(uar: &mut [u16], digits: i32, shift: i32) -> i32 {
    if shift == 0 {
        return digits;
    }
    if digits + shift <= DECDPUN {
        if let Some(first) = uar.get_mut(0) {
            *first = (*first as u32 * DECPOWERS[shift as usize] as u32) as u16;
        }
        return digits + shift;
    }
    let source_units = d2u(digits) as usize;
    let target_units = d2u(digits + shift) as usize;
    let cut = DECDPUN
        - (shift - ((target_units as i32 - source_units as i32 - 1) * DECDPUN));
    if cut == 0 {
        for i in (0..source_units).rev() {
            let target = i + target_units - source_units;
            if target < uar.len() {
                uar[target] = uar[i];
            }
            uar[i] = 0;
        }
    } else {
        let power = DECPOWERS[cut as usize] as u32;
        let inv_power = DECPOWERS[(DECDPUN - cut) as usize] as u32;
        let mut next: u32 = 0;
        for i in (0..source_units).rev() {
            let current = uar[i] as u32;
            let quot = (current >> cut as u32) * MULTIES[cut as usize] >> 17;
            let rem = current - quot * power;
            let target = i + target_units - source_units;
            if target < uar.len() {
                uar[target] = (next + quot) as u16;
            }
            next = rem * inv_power;
        }
    }
    for i in 0..(target_units - source_units) {
        if i < uar.len() {
            uar[i] = 0;
        }
    }
    digits + shift
}
/// Reverse the order of units in a slice
///
/// Swaps elements from both ends toward the middle
pub fn decReverse(lsu: &mut [u16]) {
    if lsu.len() <= 1 {
        return;
    }
    let mut lo = 0;
    let mut hi = lsu.len() - 1;
    while lo < hi {
        lsu.swap(lo, hi);
        lo += 1;
        hi -= 1;
    }
}
/// Compare two DecNumbers, returns -1, 0, or 1
fn decNumberCompare(lhs: &DecNumber, rhs: &DecNumber) -> i32 {
    let lhs_neg = lhs.is_negative();
    let rhs_neg = rhs.is_negative();
    if lhs_neg && !rhs_neg {
        return -1;
    }
    if !lhs_neg && rhs_neg {
        return 1;
    }
    let sign_mult = if lhs_neg { -1 } else { 1 };
    let lhs_adj = lhs.exponent + lhs.digits - 1;
    let rhs_adj = rhs.exponent + rhs.digits - 1;
    if lhs_adj > rhs_adj {
        return sign_mult;
    }
    if lhs_adj < rhs_adj {
        return -sign_mult;
    }
    0
}
/// Bitwise OR of two DecNumbers
pub fn decNumberOr<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    if lhs.exponent != 0 || lhs.is_special() || lhs.is_negative() || rhs.exponent != 0
        || rhs.is_special() || rhs.is_negative()
    {
        decStatus(res, DEC_INVALID_OPERATION, set);
        return res;
    }
    let lhs_units = d2u(lhs.digits) as usize;
    let rhs_units = d2u(rhs.digits) as usize;
    let res_units = d2u(set.digits) as usize;
    let msu_digits = set.digits - ((res_units as i32 - 1) * DECDPUN);
    res.lsu = vec![0; res_units];
    for i in 0..res_units {
        let a = lhs.lsu.get(i).copied().unwrap_or(0);
        let b = rhs.lsu.get(i).copied().unwrap_or(0);
        if a | b != 0 {
            let mut result: u16 = 0;
            let mut a_val = a;
            let mut b_val = b;
            for j in 0..DECDPUN {
                if (a_val | b_val) & 1 != 0 {
                    result += DECPOWERS[j as usize] as u16;
                }
                let a_digit = a_val % 10;
                let b_digit = b_val % 10;
                a_val /= 10;
                b_val /= 10;
                if a_digit > 1 || b_digit > 1 {
                    decStatus(res, DEC_INVALID_OPERATION, set);
                    return res;
                }
                if i == res_units - 1 && j == msu_digits - 1 {
                    break;
                }
            }
            res.lsu[i] = result;
        }
    }
    res.digits = decGetDigits(&res.lsu, res_units as i32);
    res.exponent = 0;
    res.bits = 0;
    res
}
/// Rotate digits of a DecNumber
pub fn decNumberRotate<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    let mut status = 0u32;
    if lhs.is_nan() || rhs.is_nan() {
        decNaNs(res, lhs, Some(rhs), set, &mut status);
    } else if rhs.is_infinite() || rhs.exponent != 0 {
        status = DEC_INVALID_OPERATION;
    } else {
        let rotate = decGetInt(rhs);
        if rotate == BADINT || rotate == BIGSEVEN || rotate == BIGEVEN
            || rotate.abs() > set.digits
        {
            status = DEC_INVALID_OPERATION;
        } else {
            decNumberCopy(res, lhs);
            let mut rot = rotate;
            if rot < 0 {
                rot = set.digits + rot;
            }
            if rot != 0 && rot != set.digits && !res.is_infinite() {
                let msu_max = d2u(set.digits) as usize;
                while res.lsu.len() < msu_max {
                    res.lsu.push(0);
                }
                res.digits = set.digits;
                let shift = set.digits - rot;
                let units = (shift / DECDPUN) as usize;
                let digit_shift = shift % DECDPUN;
                if digit_shift > 0 {
                    let power = DECPOWERS[digit_shift as usize] as u32;
                    let inv_power = DECPOWERS[(DECDPUN - digit_shift) as usize] as u32;
                    let save = res.lsu[0] as u32 % power;
                    for i in 0..res.lsu.len() - 1 {
                        let current = res.lsu[i] as u32;
                        let next = res.lsu[i + 1] as u32;
                        res.lsu[i] = ((current / power) + (next % power) * inv_power)
                            as u16;
                    }
                    if let Some(last) = res.lsu.last_mut() {
                        *last = ((*last as u32 / power) + save * inv_power) as u16;
                    }
                }
                if units > 0 {
                    let len = res.lsu.len();
                    let mut temp = vec![0u16; len];
                    for i in 0..len {
                        temp[(i + units) % len] = res.lsu[i];
                    }
                    res.lsu = temp;
                }
                res.digits = decGetDigits(&res.lsu, msu_max as i32);
            }
        }
    }
    if status != 0 {
        decStatus(res, status, set);
    }
    res
}
/// Scale B operation (multiply by power of 10)
pub fn decNumberScaleB<'a>(
    res: &'a mut DecNumber,
    lhs: &DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    let mut status = 0u32;
    let mut residue = 0i32;
    if lhs.is_nan() || rhs.is_nan() {
        decNaNs(res, lhs, Some(rhs), set, &mut status);
    } else if rhs.is_infinite() || rhs.exponent != 0 {
        status = DEC_INVALID_OPERATION;
    } else {
        let reqexp = decGetInt(rhs);
        if reqexp == BADINT || reqexp == BIGSEVEN || reqexp == BIGEVEN
            || (reqexp.abs() + 1) / 2 > (set.digits + set.emax)
        {
            status = DEC_INVALID_OPERATION;
        } else {
            decNumberCopy(res, lhs);
            if !res.is_infinite() {
                let old_exp = res.exponent;
                res.exponent += reqexp;
                if (old_exp >= 0) == (reqexp >= 0)
                    && (old_exp >= 0) != (res.exponent >= 0)
                {
                    if old_exp < 0 {
                        res.exponent = i32::MIN;
                    } else {
                        res.exponent = i32::MAX;
                    }
                }
                decFinalize(res, set, &mut residue, &mut status);
            }
        }
    }
    if status != 0 {
        decStatus(res, status, set);
    }
    res
}
/// Negate a DecNumber (unary minus)
pub fn decNumberMinus<'a>(
    res: &'a mut DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    let mut dzero = DecNumber::new();
    let mut status = 0u32;
    dzero.exponent = rhs.exponent;
    decAddOp(res, &dzero, rhs, set, DECNEG, &mut status);
    if status != 0 {
        decStatus(res, status, set);
    }
    res
}
/// Next representable number greater than rhs
pub fn decNumberNextPlus<'a>(
    res: &'a mut DecNumber,
    rhs: &DecNumber,
    set: &mut DecContext,
) -> &'a mut DecNumber {
    let mut status = 0u32;
    if rhs.bits & (DECINF | DECNEG) == (DECINF | DECNEG) {
        decSetMaxValue(res, set);
        res.bits = DECNEG;
        return res;
    }
    let mut dtiny = DecNumber::new();
    dtiny.lsu[0] = 1;
    dtiny.exponent = set.emin - 1;
    let mut workset = set.clone();
    workset.round = Rounding::Ceiling;
    decAddOp(res, rhs, &dtiny, &workset, 0, &mut status);
    status &= DEC_INVALID_OPERATION | 0x40000000;
    if status != 0 {
        decStatus(res, status, set);
    }
    res
}
/// Exponential function (internal)
pub fn decExpOp<'a>(
    res: &'a mut DecNumber,
    rhs: &DecNumber,
    set: &DecContext,
    status: &mut u32,
) -> &'a mut DecNumber {
    let mut ignore = 0u32;
    if rhs.is_special() {
        if rhs.is_infinite() {
            if rhs.is_negative() {
                decNumberZero(res);
            } else {
                decNumberCopy(res, rhs);
            }
        } else {
            decNaNs(res, rhs, None, set, status);
        }
        return res;
    }
    if rhs.is_zero() {
        decNumberZero(res);
        res.lsu[0] = 1;
        return res;
    }
    let mut d = DecNumber::new();
    d.lsu[0] = 4;
    d.exponent = -set.digits;
    if rhs.is_negative() {
        d.exponent -= 1;
    }
    let comp = decCompare(&d, rhs, true);
    if comp == BADINT {
        *status |= DEC_INSUFFICIENT_STORAGE;
        return res;
    }
    if comp >= 0 {
        let shift = set.digits - 1;
        decNumberZero(res);
        res.lsu[0] = 1;
        res.digits = decShiftToMost(&mut res.lsu, 1, shift);
        res.exponent = -shift;
        *status |= DEC_INEXACT | DEC_ROUNDED;
        return res;
    }
    let mut aset = DecContext::default_context(DEC_INIT_DECIMAL64);
    aset.emax = set.emax;
    aset.emin = set.emin;
    aset.clamp = 0;
    let p = rhs.digits.max(set.digits.max(7)) + 2;
    aset.digits = p * 2;
    let mut a = DecNumber::new();
    a.lsu[0] = 1;
    let mut t = DecNumber::new();
    decNumberCopy(&mut t, rhs);
    let mut d_val = DecNumber::new();
    d_val.lsu[0] = 2;
    let mut numone = DecNumber::new();
    numone.lsu[0] = 1;
    loop {
        let a_clone = a.clone();
        decAddOp(&mut a, &a_clone, &t, &aset, 0, status);
        let old_t = t.clone();
        decMultiplyOp(&mut t, &old_t, rhs, &aset, &mut ignore);
        let old_t2 = t.clone();
        decDivideOp(&mut t, &old_t2, &d_val, &aset, 0x80, &mut ignore);
        if (a.digits + a.exponent) >= (t.digits + t.exponent + p + 1) && a.digits >= p {
            break;
        }
        let old_d = d_val.clone();
        decAddOp(&mut d_val, &old_d, &numone, &aset, 0, &mut ignore);
    }
    let mut residue = if a.is_zero() { 0 } else { 1 };
    aset.digits = set.digits;
    decCopyFit(res, &a, &aset, &mut residue, status);
    let set_mut = &mut set.clone();
    decFinalize(res, set_mut, &mut residue, status);
    res
}
/// Natural logarithm operation (internal)
pub fn decLnOp<'a>(
    res: &'a mut DecNumber,
    rhs: &DecNumber,
    set: &DecContext,
    status: &mut u32,
) -> &'a mut DecNumber {
    let mut ignore = 0u32;
    if rhs.is_special() {
        if rhs.is_infinite() {
            if rhs.is_negative() {
                *status |= DEC_INVALID_OPERATION;
            } else {
                decNumberCopy(res, rhs);
            }
        } else {
            decNaNs(res, rhs, None, set, status);
        }
        return res;
    }
    if rhs.is_zero() {
        decNumberZero(res);
        res.bits = DECINF | DECNEG;
        return res;
    }
    if rhs.is_negative() {
        *status |= DEC_INVALID_OPERATION;
        return res;
    }
    if rhs.exponent == 0 && set.digits <= 40 {
        if rhs.lsu[0] == 10 && rhs.digits == 2 {
            let mut aset = set.clone();
            aset.round = DEC_ROUND_HALF_EVEN;
            decNumberFromString(res, "2.302585092994045684017991454684364207601", &mut aset);
            *status |= DEC_INEXACT | DEC_ROUNDED;
            return res;
        }
        if rhs.lsu[0] == 2 && rhs.digits == 1 {
            let mut aset = set.clone();
            aset.round = DEC_ROUND_HALF_EVEN;
            decNumberFromString(
                res,
                "0.6931471805599453094172321214581765680755",
                &mut aset,
            );
            *status |= DEC_INEXACT | DEC_ROUNDED;
            return res;
        }
    }
    let p = rhs.digits.max(set.digits.max(7)) + 2;
    let mut aset = DecContext::default_context(DEC_INIT_DECIMAL64);
    aset.emax = set.emax;
    aset.emin = set.emin;
    aset.clamp = 0;
    let r = rhs.exponent + rhs.digits;
    let mut a = DecNumber::new();
    decNumberFromInt32(&mut a, r);
    let mut b = DecNumber::new();
    decNumberFromInt32(&mut b, 2302585);
    b.exponent = -6;
    let a_clone = a.clone();
    decMultiplyOp(&mut a, &a_clone, &b, &aset, &mut ignore);
    let mut bset = aset.clone();
    bset.digits = 2;
    bset.round = Rounding::Down;
    let mut residue = 0i32;
    decCopyFit(&mut b, rhs, &bset, &mut residue, &mut ignore);
    b.exponent = 0;
    let t_val = decGetInt(&b);
    let t_adj = if t_val < 10 { t_val * 10 + t_val } else { t_val };
    let idx = (t_adj - 10).max(0).min(9) as usize;
    let ln_approx = LNNN[idx];
    decNumberFromInt32(&mut b, ln_approx >> 2);
    b.exponent = -((ln_approx & 3) + 3);
    b.bits = DECNEG;
    aset.digits = 16;
    aset.round = DEC_ROUND_HALF_EVEN;
    let a_clone2 = a.clone();
    decAddOp(&mut a, &a_clone2, &b, &aset, 0, &mut ignore);
    let mut numone = DecNumber::new();
    numone.lsu[0] = 1;
    bset = aset.clone();
    bset.emax = 999999 * 2;
    bset.emin = -999999 * 2;
    let mut pp = 9;
    aset.digits = pp;
    bset.digits = pp + rhs.digits;
    loop {
        let mut neg_a = a.clone();
        neg_a.bits ^= DECNEG;
        decExpOp(&mut b, &neg_a, &bset, &mut ignore);
        let old_b = b.clone();
        decMultiplyOp(&mut b, &old_b, rhs, &bset, &mut ignore);
        let old_b2 = b.clone();
        decAddOp(&mut b, &old_b2, &numone, &bset, DECNEG, &mut ignore);
        if b.is_zero()
            || (a.digits + a.exponent) >= (b.digits + b.exponent + set.digits + 1)
        {
            if a.digits == p {
                break;
            }
            if a.is_zero() {
                let mut cmp = DecNumber::new();
                let mut aset_mut = aset.clone();
                decCompareOp(&mut cmp, rhs, &numone, &mut aset_mut, 0x01, &mut ignore);
                if cmp.lsu[0] == 0 {
                    a.exponent = 0;
                } else {
                    *status |= DEC_INEXACT | DEC_ROUNDED;
                }
                break;
            }
            if b.is_zero() {
                b.exponent = a.exponent - p;
            }
        }
        let old_a = a.clone();
        decAddOp(&mut a, &old_a, &b, &aset, 0, &mut ignore);
        if pp >= p {
            continue;
        }
        pp = (pp * 2).min(p);
        aset.digits = pp;
        bset.digits = pp + rhs.digits;
    }
    residue = if a.is_zero() { 0 } else { 1 };
    aset.digits = set.digits;
    decCopyFit(res, &a, &aset, &mut residue, status);
    let set_mut = &mut set.clone();
    decFinalize(res, set_mut, &mut residue, status);
    res
}
const DEC_DIVISION_BY_ZERO: u32 = 0x00000002;
