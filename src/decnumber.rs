/// Convert digits to units
fn digits_to_units(digits: i32) -> i32 {
    if digits <= 49 {
        D2UTABLE[digits as usize]
    } else {
        (digits + DECDPUN - 1) / DECDPUN
    }
}
/// Compare a target string against two reference strings character by character.
/// Returns 1 (true) if every character in `targ` matches the corresponding character
/// in either `str1` or `str2`. Returns 0 (false) if any character mismatches both.
///
/// This is typically used for case-insensitive or variant string comparison
/// where either uppercase or lowercase versions are acceptable.
///
/// # Arguments
/// * `targ` - The target string to check
/// * `str1` - First reference string (e.g., uppercase version)
/// * `str2` - Second reference string (e.g., lowercase version)
///
/// # Returns
/// * `1` if all characters match either str1 or str2
/// * `0` if any character fails to match both
pub fn decBiStr(targ: &str, str1: &str, str2: &str) -> u8 {
    let targ_bytes = targ.as_bytes();
    let str1_bytes = str1.as_bytes();
    let str2_bytes = str2.as_bytes();
    let mut idx = 0;
    loop {
        let t = targ_bytes.get(idx).copied().unwrap_or(0);
        let s1 = str1_bytes.get(idx).copied().unwrap_or(0);
        let s2 = str2_bytes.get(idx).copied().unwrap_or(0);
        if t != s1 && t != s2 {
            return 0;
        }
        if t == 0 {
            break;
        }
        idx += 1;
    }
    1
}
